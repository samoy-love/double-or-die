export interface ContrastPair {
  a: string;
  b: string;
  /** Зачем эту пару вообще различать: строка попадает в отчёт гейта. */
  why: string;
  /**
   * Свой порог, если общий здесь не к месту.
   *
   * Порогов два, и второй появился не ради зелёного гейта. Экранных ролей у
   * игры семнадцать — четыре игрока, три врага, фишка, контур карты,
   * телеграф, снаряд, шесть категорий пари и общая заливка, — а палитра
   * столько взаимно далёких цветов не вмещает: арифметика, а не вкус.
   *
   * Разводить надо то, что живёт в одном слое и решается за долю секунды:
   * игрок против врага, телеграф против того, кто атакует, снаряд против
   * фона. Категория пари в этот класс не входит: она никогда не оказывается
   * на месте игрока или врага — только на карте и её луче, — и первым
   * признаком у неё служит ФОРМА иконки, а цвет вторым (GDD §7, §21).
   * Требовать от неё той же разницы значило бы испортить обе шкалы разом.
   */
  min?: number;
}

/**
 * Мягкий порог: цвета не совпадают, но различает их форма, а не цвет.
 *
 * Не «поблажка для неудобных пар»: ниже него цвета читаются как один и тот
 * же, и никакая форма этого уже не вытянет.
 */
export const DELTA_E_SOFT = 12;

function cross(
  as: readonly string[],
  bs: readonly string[],
  why: string,
  min?: number,
): ContrastPair[] {
  const out: ContrastPair[] = [];
  // Ключ `min` не пишется вовсе, когда порога нет: `min: undefined` и
  // отсутствие ключа — разные вещи для строгой типизации, и первое означало
  // бы «порог задан и он никакой».
  for (const a of as)
    for (const b of bs) out.push(min === undefined ? { a, b, why } : { a, b, why, min });
  return out;
}

