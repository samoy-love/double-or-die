/**
 * Проверка контраста палитры по ΔE.
 *
 * Читаемость объявлена столпом дизайна (GDD §5), и проверять её «на глаз»
 * нельзя: глаз привыкает к своей же палитре за неделю, и разница, которой
 * автор не замечает, для нового игрока не существует. ΔE меряет ровно то, что
 * видит человек, — расстояние в перцептивном пространстве, а не в RGB, где два
 * одинаково далёких числа выглядят по-разному далёкими.
 *
 * Модуль намеренно чистый: ни `window`, ни `document`, ни канваса. Его
 * вызывает и юнит-тест, и отдельный гейт CI — а гейт живёт в Node, где ни
 * того, ни другого нет.
 *
 * Считается CIEDE2000, а не CIE76. Разница здесь не академическая: почти вся
 * палитра — насыщенные цвета, а евклидово расстояние в Lab систематически
 * завышает различимость именно на них. Синий телеграф и фиолетовый Фитиль по
 * CIE76 «различимы» с запасом, хотя в мельтешении глаз их путает; поправки на
 * насыщенность (`Sc`) и на оттенок (`Sh`, `Rt`) — это ровно то, ради чего
 * формулу и берут.
 */

import { ENTITY_FILL, PALETTE, type Rgb } from './palette';

// ---------------------------------------------------------------------------
// sRGB → CIELAB
// ---------------------------------------------------------------------------

export interface Lab {
  L: number;
  a: number;
  b: number;
}

/** Компанда sRGB: канал 0..1 в линейный свет. */
const linear = (v: number): number => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4);

/**
 * sRGB → CIE XYZ при D65 и дальше в CIELAB.
 *
 * Белая точка D65, потому что игра живёт в браузере, а sRGB определён именно
 * в ней: считать в D50 значило бы мерить цвета чужого монитора.
 */
export function toLab(c: Rgb): Lab {
  const r = linear(c.r);
  const g = linear(c.g);
  const b = linear(c.b);

  // Матрица sRGB → XYZ (D65), нормированная на белую точку.
  const x = (r * 0.4124564 + g * 0.3575761 + b * 0.1804375) / 0.95047;
  const y = r * 0.2126729 + g * 0.7151522 + b * 0.072175;
  const z = (r * 0.0193339 + g * 0.119192 + b * 0.9503041) / 1.08883;

  // Кубический корень с линейным продолжением у нуля: без него тёмные цвета
  // уходят в бесконечную производную, а фон здесь как раз тёмный.
  const f = (v: number): number => (v > 216 / 24389 ? Math.cbrt(v) : (841 / 108) * v + 4 / 29);
  const fx = f(x);
  const fy = f(y);
  const fz = f(z);

  return { L: 116 * fy - 16, a: 500 * (fx - fy), b: 200 * (fy - fz) };
}

const rad = (d: number): number => (d * Math.PI) / 180;
const deg = (r: number): number => (r * 180) / Math.PI;

/**
 * CIEDE2000 между двумя цветами палитры.
 *
 * Формула громоздкая, и переписывать её «попроще» не надо: поправки на
 * насыщенность и оттенок — это и есть вся разница с евклидовым расстоянием.
 */
export function deltaE(c1: Rgb, c2: Rgb): number {
  const l1 = toLab(c1);
  const l2 = toLab(c2);

  const C1 = Math.hypot(l1.a, l1.b);
  const C2 = Math.hypot(l2.a, l2.b);
  const Cbar = (C1 + C2) / 2;
  const G = 0.5 * (1 - Math.sqrt(Cbar ** 7 / (Cbar ** 7 + 25 ** 7)));

  const a1 = (1 + G) * l1.a;
  const a2 = (1 + G) * l2.a;
  const Cp1 = Math.hypot(a1, l1.b);
  const Cp2 = Math.hypot(a2, l2.b);

  const hue = (a: number, b: number): number => {
    if (a === 0 && b === 0) return 0;
    const h = deg(Math.atan2(b, a));
    return h < 0 ? h + 360 : h;
  };
  const hp1 = hue(a1, l1.b);
  const hp2 = hue(a2, l2.b);

  const dL = l2.L - l1.L;
  const dC = Cp2 - Cp1;

  let dhp = 0;
  if (Cp1 * Cp2 !== 0) {
    dhp = hp2 - hp1;
    if (dhp > 180) dhp -= 360;
    else if (dhp < -180) dhp += 360;
  }
  const dH = 2 * Math.sqrt(Cp1 * Cp2) * Math.sin(rad(dhp) / 2);

  const Lbar = (l1.L + l2.L) / 2;
  const Cpbar = (Cp1 + Cp2) / 2;

  let hbar = hp1 + hp2;
  if (Cp1 * Cp2 !== 0) {
    if (Math.abs(hp1 - hp2) > 180) hbar += hp1 + hp2 < 360 ? 360 : -360;
    hbar /= 2;
  }

  const T =
    1 -
    0.17 * Math.cos(rad(hbar - 30)) +
    0.24 * Math.cos(rad(2 * hbar)) +
    0.32 * Math.cos(rad(3 * hbar + 6)) -
    0.2 * Math.cos(rad(4 * hbar - 63));

  const Sl = 1 + (0.015 * (Lbar - 50) ** 2) / Math.sqrt(20 + (Lbar - 50) ** 2);
  const Sc = 1 + 0.045 * Cpbar;
  const Sh = 1 + 0.015 * Cpbar * T;
  const Rt =
    -2 *
    Math.sqrt(Cpbar ** 7 / (Cpbar ** 7 + 25 ** 7)) *
    Math.sin(rad(60 * Math.exp(-(((hbar - 275) / 25) ** 2))));

  return Math.sqrt((dL / Sl) ** 2 + (dC / Sc) ** 2 + (dH / Sh) ** 2 + Rt * (dC / Sc) * (dH / Sh));
}

