/** Все пары внутри одного набора: каждая с каждой, без повторов. */
function pairsWithin(names: readonly string[], why: string): ContrastPair[] {
  const out: ContrastPair[] = [];
  for (let i = 0; i < names.length; i++) {
    for (let j = i + 1; j < names.length; j++) out.push({ a: names[i], b: names[j], why });
  }
  return out;
}

export interface ContrastResult extends ContrastPair {
  deltaE: number;
  ok: boolean;
}

