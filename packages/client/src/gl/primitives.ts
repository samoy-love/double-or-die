/**
 * Модульные примитивы отрисовки: форма/цвет/семисегментные цифры.
 *
 * Ничего игрового — только `ShapeBatch`/`Shape`/`Rgb`. Вынесены из
 * `renderer.ts` как чистые функции без побочных эффектов на состояние
 * класса `Renderer` (см. разведку переноса).
 */
import { Shape, ShapeBatch } from './batch';
import { ENTITY_FILL, type Rgb } from '../palette';

/** Толщина обводки из арт-дирекшна: 4 u на всём (GDD §21). */
export const STROKE = 4;

/**
 * Сущность арены: тёмная заливка плюс несущая обводка цветом роли.
 *
 * Отдельная функция, а не пятнадцать одинаковых `push()` подряд: правило
 * «заливка одна на всех» должно нарушаться в одном месте, а не разъезжаться по
 * файлу — именно так до редизайна и накопилось семнадцать разных заливок.
 * Заодно вызов перестаёт быть стеной из пятнадцати чисел, в которой не видно,
 * какой цвет несущий.
 *
 * `stroke` меньше общей толщины задаётся там, где фигура мельче обводки
 * (метки, кольца в строке расчёта): четыре единицы на радиусе семь — это уже
 * не обводка, а заливка.
 */
export function entity(
  b: ShapeBatch,
  shape: Shape,
  x: number,
  y: number,
  halfW: number,
  halfH: number,
  rotation: number,
  role: Rgb,
  alpha = 1,
  stroke = STROKE,
): void {
  b.push(
    shape,
    x,
    y,
    halfW,
    halfH,
    rotation,
    ENTITY_FILL.r,
    ENTITY_FILL.g,
    ENTITY_FILL.b,
    alpha,
    stroke,
    role.r,
    role.g,
    role.b,
    alpha,
  );
}

/**
 * Безопасный отступ от левой/правой кромки арены для содержимого, стоящего
 * вплотную к краю (боевой HUD) — доля от ШИРИНЫ АРЕНЫ, а не константа.
 *
 * Экран подгоняется под вьюпорт способом cover, а не letterbox (см.
 * `render()`): вместо чёрных полос сверху/снизу игра обрезает арену по
 * бокам, если вьюпорт УЖЕ, чем родные 16:9. Проект держит 8:5 (Steam
 * Deck, 1280×800) нижней границей поддерживаемых форм-факторов — на ней
 * обрезается `(1 − 8/5 ÷ 16/9) / 2 = 5%` ширины арены с каждой стороны,
 * НЕЗАВИСИМО от состава: коопная арена шире соло на 8% за каждого
 * лишнего игрока, но остаётся тем же 16:9, и 5% берутся от уже
 * увеличенной ширины. Раньше HUD стоял на фиксированных 40 единицах от
 * края — на соло 1920 это 2%, меньше обрезаемой на Deck полосы, и
 * колонка HUD уезжала за кадр первой; фиксированная константа вместо
 * доли решала бы это только для соло и снова уезжала бы вчетвером.
 */
export const edgeSafeX = (arenaW: number): number => arenaW * 0.05;

export const lerp = (a: number, b: number, t: number): number => a + (b - a) * t;
export const clamp01 = (v: number): number => (v < 0 ? 0 : v > 1 ? 1 : v);

/**
 * Свечение — мягкий ореол вокруг сущности.
 *
 * Настоящее свечение — это шейдерный проход (PRODUCTION §4, стадия F4), и он
 * стоит там же, где виньетка. До него ореол собирается тем же батчем: два-три
 * кольца растущего радиуса с падающей прозрачностью. Приём тот же, что у
 * виньетки пола, и по той же причине — одна толстая фигура даёт полосу с
 * резким краем, а несколько тонких читаются градиентом.
 *
 * Нужен он не для красоты: без ореола сущности на общей тёмной заливке
 * держатся на четырёх пикселях обводки, и арена читается плоской россыпью
 * контуров. Свечение возвращает иерархию — светится то, что в ней выше
 * (GDD §21): снаряды ярче игрока, игрок ярче фишек, фон не светится вовсе.
 */
export function glow(
  b: ShapeBatch,
  shape: Shape,
  x: number,
  y: number,
  rx: number,
  c: Rgb,
  a: number,
  ry = rx,
): void {
  for (let i = 1; i <= 3; i++) {
    const k = 1 + i * 0.34;
    b.push(shape, x, y, rx * k, ry * k, 0, 0, 0, 0, 0, 2, c.r, c.g, c.b, (a * (4 - i)) / 9);
  }
}

/** Развёртка цвета в три аргумента push(): читается лучше, чем три поля подряд. */
export const channels = (c: Rgb): [number, number, number] => [c.r, c.g, c.b];

/**
 * Число семисегментными палочками, по центру относительно `x`.
 *
 * Цифры остались палочками и после того, как в игру приехал шрифт. Причина не
 * в экономии: семисегментное табло — это язык самого заведения, оно читается с
 * дивана на любом кегле и не зависит ни от языка, ни от гарнитуры, включая
 * шрифт для дислексии (UX §5). Семь отрезков — семь инстансов на цифру, тот же
 * батч и ни одной выборки из атласа в горячем HUD.
 *
 * Центрируется всё число целиком, а не первая его цифра: раньше `x` был левым
 * краем, и таймер в кольце приходилось двигать поправкой на глаз — она
 * подходила однозначным числам и мазала на всех остальных.
 */
const SEGMENTS: readonly number[] = [
  0b1110111, 0b0100100, 0b1011101, 0b1101101, 0b0101110, 0b1101011, 0b1111011, 0b0100101, 0b1111111,
  0b1101111,
];

export function drawNumber(
  b: ShapeBatch,
  value: number,
  x: number,
  y: number,
  size: number,
  c: Rgb,
  a = 1,
): void {
  const text = String(Math.max(0, Math.trunc(value)));
  const w = size * 0.6;
  // Толщина палочки: не тоньше двух единиц, иначе цифра пропадает в растре.
  const t = Math.max(2, size * 0.2);
  const advance = w * 2 + size * 0.5;
  const left = x - (advance * (text.length - 1)) / 2;

  for (let i = 0; i < text.length; i++) {
    const digit = text.charCodeAt(i) - 48;
    const mask = SEGMENTS[digit] ?? 0;
    // Единица горит только правой парой отрезков и потому висит в своей
    // клетке справа. Сдвигаем её к середине — иначе «1» в кольце таймера
    // стоит не там, где все остальные цифры.
    const cx = left + i * advance - (digit === 1 ? w : 0);
    // Порядок битов: верх, левый верх, правый верх, середина, левый низ,
    // правый низ, низ.
    if (mask & 0b0000001) hbar(b, cx, y - size, w, t, c, a);
    if (mask & 0b0000010) vbar(b, cx - w, y - size / 2, size / 2, t, c, a);
    if (mask & 0b0000100) vbar(b, cx + w, y - size / 2, size / 2, t, c, a);
    if (mask & 0b0001000) hbar(b, cx, y, w, t, c, a);
    if (mask & 0b0010000) vbar(b, cx - w, y + size / 2, size / 2, t, c, a);
    if (mask & 0b0100000) vbar(b, cx + w, y + size / 2, size / 2, t, c, a);
    if (mask & 0b1000000) hbar(b, cx, y + size, w, t, c, a);

    /*
     * Единице — засечка и полка, иначе она не цифра, а палочка.
     *
     * Семисегментная «1» — это два правых отрезка и больше ничего, и в
     * одиночку она не читается числом вовсе: на экране итогов «Этаж 1» и
     * «Ключи 1» выглядели двумя одинаковыми штрихами рядом с подписями, то
     * есть главное число забега пропадало. Табло-шрифты решают это ровно так
     * же — диагональным флажком сверху и полкой снизу; сегментов при этом
     * по-прежнему семь, добавлены две служебные планки, и только у единицы.
     */
    if (digit === 1) {
      const stem = cx + w;
      b.push(
        Shape.Box,
        stem - w * 0.34,
        y - size + w * 0.34,
        w * 0.5,
        t / 2,
        -Math.PI / 4,
        c.r,
        c.g,
        c.b,
        a,
        0,
        0,
        0,
        0,
        0,
      );
      hbar(b, stem, y + size, w * 0.8, t, c, a);
    }
  }
}

/**
 * Множитель: «×» и число с одной десятой.
 *
 * Десятая обязательна: в каталоге живут ×2.5 и ×3.5 (GDD §9.5), и округление
 * до целого врёт про выплату ровно в тех пари, которые игрок берёт ради
 * жирного куша. Целая часть однозначна по построению — множитель одного пари
 * не доходит до десяти даже на боссах.
 */
export function drawMultiplier(
  b: ShapeBatch,
  m: number,
  x: number,
  y: number,
  size: number,
  c: Rgb,
  a = 1,
): void {
  const step = size * 1.8;
  // Крестик «×»: два отрезка, а не глиф — множитель стоит рядом с
  // семисегментными цифрами и обязан быть их роста, а не роста гарнитуры.
  for (const angle of [Math.PI / 4, -Math.PI / 4]) {
    b.push(
      Shape.Box,
      x,
      y,
      size * 0.55,
      Math.max(2, size * 0.16),
      angle,
      c.r,
      c.g,
      c.b,
      a,
      0,
      0,
      0,
      0,
      0,
    );
  }

  const whole = Math.trunc(m);
  const tenth = Math.round((m - whole) * 10);
  drawNumber(b, whole, x + step, y, size, c, a);
  if (tenth === 0) return;

  const t = Math.max(2, size * 0.2);
  b.push(Shape.Box, x + step * 1.6, y + size, t, t, 0, c.r, c.g, c.b, a, 0, 0, 0, 0, 0);
  drawNumber(b, tenth, x + step * 2.3, y, size, c, a);
}

export const hbar = (
  b: ShapeBatch,
  x: number,
  y: number,
  w: number,
  t: number,
  c: Rgb,
  a: number,
): void => {
  b.push(Shape.Box, x, y, w, t, 0, c.r, c.g, c.b, a, 0, 0, 0, 0, 0);
};

export const vbar = (
  b: ShapeBatch,
  x: number,
  y: number,
  h: number,
  t: number,
  c: Rgb,
  a: number,
): void => {
  b.push(Shape.Box, x, y, t, h, 0, c.r, c.g, c.b, a, 0, 0, 0, 0, 0);
};
