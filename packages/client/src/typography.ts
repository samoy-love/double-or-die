/**
 * Типографическая шкала интерфейса — единственное место, где живут кегли.
 *
 * Заводится по той же причине, что и палитра: правило «минимальный размер
 * текста — 24 px при 1080p» (UX §4) невозможно соблюдать, пока кегль
 * вписывается числом в место вызова. Арена — ровно 1920×1080 единиц
 * (`ARENA_W/H`), то есть единица равна пикселю при 1080p, и вписанные «12»,
 * «13», «14» были не «мелко на вкус», а вдвое ниже собственного порога: на
 * экране двери подсказка набиралась двенадцатью пикселями, на расчёте имя
 * пари — тринадцатью.
 *
 * Ступеней намеренно мало. Шкала из пяти кеглей заставляет выбирать роль
 * («это подпись или это тело?»), а шкала из тринадцати — подбирать число на
 * глаз, и разъезжается она в первой же правке.
 *
 * `MIN` — не ступень, а гейт: любой кегль ниже него — дефект, и проверяется
 * это тестом (`tests/typography.test.ts`), а не вниманием на ревью.
 */
export const TEXT = {
  /** Титул главного меню — единственная надпись такого роста в игре. */
  hero: 64,
  /** Титул экрана: расчёт, дверь, лавка, итоги, справка. Акцидентная. */
  title: 44,
  /** Подзаголовок под титулом: одна строка, что происходит. */
  subtitle: 26,
  /** Надпись на кнопке и имя карточки — то, по чему выбирают. */
  card: 26,
  /** Крупная кнопка: «Играть», «Ещё разок». */
  button: 30,
  /** Тело: описания, подсказки клавиш, подписи значений, реплики Крупье. */
  body: 24,
  /** Порог из UX §4. Ниже — дефект, а не решение. */
  MIN: 24,
} as const;

/**
 * Межстрочный шаг: кегль плюс четверть.
 *
 * Общий для всех переносов, потому что перенос в игре один (`wrapped`), а
 * разные шаги в разных карточках читаются как разные уровни текста.
 */
export const lineStep = (size: number): number => size * 1.28;

/**
 * Вертикальный каркас экрана — смещения от центра арены.
 *
 * Титулы стояли на семи разных высотах (−300 у справки, −150 у Ставки
 * Крупье), и при переходе между экранами заголовок прыгал по экрану, хотя
 * говорит он всегда одно и то же — «где вы сейчас». Каркас общий: экраны
 * различаются телом, а не рамкой вокруг него.
 */
export const SCREEN = {
  /** Титул экрана. */
  titleY: -330,
  /** Подзаголовок под титулом. */
  subtitleY: -272,
  /** Первая строка подсказок внизу и шаг между ними. */
  hintY: 300,
  hintStep: 36,
} as const;
