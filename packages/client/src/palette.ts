export const css = (c: Rgb): string =>
  `rgb(${Math.round(c.r * 255)} ${Math.round(c.g * 255)} ${Math.round(c.b * 255)})`;

/**
 * Цвета страницы: те же значения, но под именами, которые понимает CSS.
 *
 * Раньше `style.css` был исключён из линтера палитры с обоснованием «ради трёх
 * правил заводить генератор переменных дороже, чем стоит выгода». Редизайн
 * 0.4.0 эту цену предъявил: палитра сменилась целиком, а фон страницы остался
 * прежним, фиолетовым, — и не заметил никто, потому что единственная проверка,
 * которая могла бы заметить, этот файл не читала. Правил стало шесть, впереди
 * экраны забега, и сторона выгоды перевесила.
 *
 * Применяется на старте, до первого кадра. Начальный фон при этом всё равно
 * задан в разметке — иначе между загрузкой страницы и запуском скрипта мелькал
 * бы белый лист; тот цвет проверяется правилом для разметки и разъехаться с
 * палитрой не может.
 */
export function applyCssVariables(root: HTMLElement): void {
  const vars: Record<string, Rgb> = {
    'dod-bg': PALETTE.background,
    'dod-floor': PALETTE.floor,
    'dod-chrome': PALETTE.chrome,
    'dod-accent': PALETTE.accent,
    'dod-text': PALETTE.hudText,
    'dod-dim': PALETTE.hudDim,
    'dod-danger': PALETTE.danger,
  };
  for (const [name, c] of Object.entries(vars)) root.style.setProperty(`--${name}`, css(c));

  /*
   * Тени — из токенов высоты дизайн-системы, а не из палитры.
   *
   * Палитра описывает РОЛИ: что игрок должен различать. Тень роли не несёт, в
   * замере ΔE не участвует и под дальтоника не перекрашивается — это глубина,
   * а не цвет. Держать её здесь пришлось только потому, что линтеру палитры
   * всё равно, чем именно захардкожен цвет в CSS, и он прав: `rgb(0 0 0 / .4)`
   * посреди таблицы стилей ничем не лучше шестнадцатеричного.
   */
  for (const [name, value] of Object.entries(SHADOWS)) {
    root.style.setProperty(`--${name}`, value);
  }
}

/** Высоты из дизайн-системы samoy.love (`tokens/elevation.css`). */
const SHADOWS: Readonly<Record<string, string>> = {
  'dod-shadow-md': '0 6px 20px rgba(0, 0, 0, 0.35)',
  'dod-shadow-lg': '0 18px 48px rgba(0, 0, 0, 0.45)',
};
