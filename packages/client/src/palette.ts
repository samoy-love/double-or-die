/**
 * Единственное место, где живут цвета.
 *
 * Захардкоженный цвет в коде отрисовки ловится линтером. Причина не в
 * аккуратности: перекраска под дальтоника, смена настроения биома и проверка
 * контраста по ΔE должны делаться в одном месте, иначе три палитры разъедутся
 * и «двойное кодирование формой и цветом» перестанет работать.
 *
 * Иерархия читаемости (GDD §21), сверху вниз по яркости:
 * снаряды → телеграфы → игроки → карты и лучи → Туз → фишки → декор → фон.
 */

export interface Rgb {
  r: number;
  g: number;
  b: number;
}

const hex = (v: number): Rgb => ({
  r: ((v >> 16) & 0xff) / 255,
  g: ((v >> 8) & 0xff) / 255,
  b: (v & 0xff) / 255,
});

