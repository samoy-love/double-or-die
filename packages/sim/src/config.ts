export interface EnemyStats {
  readonly type: EnemyType;
  readonly hp: number;
  /** Цена в очках угрозы: из неё набирается бюджет волны (DIFFICULTY §3). */
  readonly threat: number;
  readonly radius: Fx;
  /** Скорость сближения вне атаки. */
  readonly speed: Fx;
  /** Длительность телеграфа в тиках. Главный рычаг честности (DIFFICULTY §11). */
  readonly telegraphTicks: number;
  readonly attackTicks: number;
  readonly recoverTicks: number;
  /**
   * С какого этажа и с какой комнаты тип входит в раскладку волн.
   *
   * Пара, а не одно число: комната нумеруется ВНУТРИ этажа, и «с пятой
   * комнаты» без этажа означало бы, что враг второго этажа появляется ещё
   * на первом. Расписание на все девять врагов — в DIFFICULTY §7, и оно
   * проверяется тестом, а не следует из удачно расставленных чисел.
   */
  readonly unlockFloor: number;
  readonly unlockRoom: number;
}

