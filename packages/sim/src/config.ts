/**
 * Симуляционный конфиг: все числа, влияющие на детерминированное поведение.
 *
 * Здесь и только здесь. Число, вписанное по месту в логику, невозможно ни
 * пересмотреть балансировщиком, ни свести с документом, ни выкатить целиком —
 * а симуляционный конфиг выкатывается именно целиком и входит в хеш
 * совместимости лобби (TECH §8.3).
 *
 * Две дисциплины, обе обязательные:
 *
 *   — **Время только в тиках.** Секунда в конфиге симуляции — это готовый
 *     десинк между 60 и 144 Гц. Секунды живут в комментариях, для людей.
 *   — **Значения в Q16.16.** Всё, что попадает в состояние, считается
 *     целыми: float-накопление позиции расходится между движками.
 *
 * Источники чисел: [GDD §6](../../../docs/GDD.md) — игрок и сочность,
 * [DIFFICULTY §3–§7](../../../docs/DIFFICULTY.md) — враги, бюджеты, честность,
 * [ECONOMY §4](../../../docs/ECONOMY.md) — дроп фишек.
 */

import { type Fx, fromFloat, fromInt } from './fixed';
import { ANGLE_FULL } from './trig';

export const TICK_HZ = 60;

/** Секунды в тики. Только для констант этого файла — в логике секунд нет. */
const ticks = (seconds: number): number => Math.round(seconds * TICK_HZ);

/** Скорость «единиц в секунду» в приращение за тик, в Q16.16. */
const perTick = (unitsPerSecond: number): Fx => fromFloat(unitsPerSecond / TICK_HZ);

/** Градусы в наши единицы угла (полный оборот — ANGLE_FULL). */
const degrees = (deg: number): number => Math.round((deg * ANGLE_FULL) / 360);

