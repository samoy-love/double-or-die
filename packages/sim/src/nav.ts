/**
 * Навигация: поля потока, видимость, обход препятствий.
 *
 * Слой отвечает на один вопрос — «куда шагнуть отсюда, чтобы оказаться там» —
 * и отвечает на него для ВСЕЙ арены сразу, а не для каждого врага отдельно.
 *
 * ПОЧЕМУ ПОЛЕ ПОТОКА, А НЕ ПОИСК ПУТИ НА КАЖДОГО
 *
 * Врагов на арене до восьмидесяти пяти, и цель у них общая — игрок. Отдельный
 * A* на каждого считал бы восемьдесят пять раз одно и то же и стоил бы кадра;
 * поле потока считается один раз от цели волной по сетке, после чего каждый
 * враг берёт из своей клетки готовое направление за одно обращение к массиву.
 * Стоимость перестаёт зависеть от числа врагов — а именно оно и растёт с
 * версиями: кооп множит толпу, боссы добавляют своих.
 *
 * ЧТО ЭТО ДАЁТ ЧЕРЕЗ НЕСКОЛЬКО ВЕРСИЙ
 *
 * Слой умышленно шире сегодняшней нужды, потому что менять несущий алгоритм
 * задним числом дороже, чем заложить его сразу:
 *
 *   — **0.4.0, двенадцать шаблонов арен.** Геометрия перестаёт быть одной
 *     заученной расстановкой, и «идти на игрока по прямой» перестаёт работать
 *     где угодно, кроме текущей комнаты. Поле строится из геометрии, какой бы
 *     она ни была.
 *   — **0.5.0, кооп.** Полей столько, сколько живых игроков: враг идёт к
 *     СВОЕЙ цели, а не к ближайшей, иначе потолок агро (не больше 40% на
 *     одного) обходится сам собой.
 *   — **0.7.0, остальные шесть врагов.** Забрало обязано заходить за спину —
 *     это поле к точке позади цели. Вьюн ищет фишки на полу и убегает —
 *     поле к ближайшей фишке и разворот потока. Луч почти неподвижен и бьёт
 *     через арену — ему нужна прямая видимость, а не путь. Всё это здесь уже
 *     есть.
 *
 * ПРЕДСКАЗУЕМОСТЬ НЕ ПОСТРАДАЛА
 *
 * Правила атак остаются прежними и остаются жёсткими: телеграф обязателен,
 * таран Клина летит строго по прямой без наведения, потолок объявленных атак
 * держится. Умнее становится не решение «когда бить», а исполнение «как дойти».
 * Игрок по-прежнему учит поведение, а не угадывает его — просто враг перестал
 * застревать в колонне.
 *
 * ДЕТЕРМИНИЗМ
 *
 * Всё целочисленное, порядок обхода фиксирован, обращений к RNG нет. Поле —
 * чистая функция от геометрии и позиций целей, поэтому в состояние оно не
 * входит и в хеш не попадает: после восстановления снимка достаточно
 * пересчитать. Кэш живёт в модульных буферах и переиспользуется — аллокаций
 * в горячем пути нет.
 */

import { hitsColumn } from './arena';
import { ARENA_PAD, NAV } from './config';
import { type Fx, fromInt, sub } from './fixed';
import { MAX_PLAYERS, Meta, RunPhase, type SimState, EntityFlag } from './state';

/** Сторона клетки сетки. Число живёт в конфиге: оно влияет на движение. */
const CELL = NAV.cell;

/** Потолок сетки: арена растёт с составом, 4 игрока дают 2380×1338. */
const MAX_COLS = 48;
const MAX_ROWS = 28;
const MAX_CELLS = MAX_COLS * MAX_ROWS;

/** Непроходимо. Больше любой достижимой стоимости. */
const BLOCKED = 0x3fffffff;

/**
 * Диагональ стоит 14 против 10 у прямой — целочисленное приближение √2.
 * Дробей здесь быть не может: поле влияет на движение, а движение — на хеш.
 */
const STRAIGHT = 10;
const DIAGONAL = 14;

const DX = [1, -1, 0, 0, 1, 1, -1, -1] as const;
const DY = [0, 0, 1, -1, 1, -1, 1, -1] as const;

/** Статическая проходимость: единица — стена или колонна. */
const blocked = new Uint8Array(MAX_CELLS);
/** Стоимость пути до цели по клеткам, одно поле на игрока. */
const cost = [
  new Int32Array(MAX_CELLS),
  new Int32Array(MAX_CELLS),
  new Int32Array(MAX_CELLS),
  new Int32Array(MAX_CELLS),
];
/** Очередь волны. Предаллоцирована: BFS не имеет права аллоцировать. */
const queue = new Int32Array(MAX_CELLS);
/** Тик последнего пересчёта поля игрока. */
const built = new Int32Array(MAX_PLAYERS).fill(-1);

let cols = 0;
let rows = 0;
/** Признак того, что сетка построена под текущую геометрию. */
let gridKey = -1;

/**
 * Чьё состояние сейчас в кэше.
 *
 * Без этой привязки кэш — источник недетерминизма, а не ускорения. Буферы
 * живут на модуле, а состояний в процессе много: CI гоняет тысячи забегов
 * подряд, и второй забег на том же сиде начинался бы с полем, посчитанным для
 * первого. Тик при этом снова ноль, расписание пересчёта молчит, и хеши
 * расходятся — ровно то, что поймала проверка «один сид даёт один хеш».
 *
 * Сравниваем по ссылке: она и есть идентичность состояния.
 */
let owner: SimState | null = null;

/** Как часто пересчитывать поле. Обоснование числа — в конфиге. */
const REBUILD_EVERY = NAV.rebuildEvery;

/** Тик прошлого вызова: по нему видно перемотку времени назад. */
let lastTick = -1;

/**
 * Метка восстановления снимка, увиденная в прошлый раз.
 *
 * Начальное значение −1 недостижимо для счётчика, который растёт от нуля,
 * поэтому первый же вызов на новом состоянии строит поле заново, а не верит
 * совпадению.
 */
let lastEpoch = -1;

const index = (cx: number, cy: number): number => cy * cols + cx;

/** Клетка, в которой лежит точка. Значения зажаты сеткой, а не проверяются. */
export const cellX = (x: Fx): number => {
  const v = (x >> 16) / CELL;
  const i = v < 0 ? 0 : v | 0;
  return i >= cols ? cols - 1 : i;
};
export const cellY = (y: Fx): number => {
  const v = (y >> 16) / CELL;
  const i = v < 0 ? 0 : v | 0;
  return i >= rows ? rows - 1 : i;
};

/**
 * Построить статическую сетку проходимости.
 *
 * Клетка непроходима, если её центр внутри колонны или ближе радиуса тела к
 * границе арены. Радиус берётся с запасом на самое крупное тело — иначе
 * Кирпич застревал бы там, где Фитиль проходит, и поле врало бы половине
 * арены.
 */
function buildGrid(s: SimState): void {
  cols = Math.min(MAX_COLS, Math.ceil((s.arenaW >> 16) / CELL));
  rows = Math.min(MAX_ROWS, Math.ceil((s.arenaH >> 16) / CELL));

  const body = NAV.bodyRadius;
  const pad = ARENA_PAD;

  for (let cy = 0; cy < rows; cy++) {
    for (let cx = 0; cx < cols; cx++) {
      const x = fromInt(cx * CELL + CELL / 2);
      const y = fromInt(cy * CELL + CELL / 2);
      const outside =
        x < pad + body ||
        y < pad + body ||
        x > sub(s.arenaW, pad + body) ||
        y > sub(s.arenaH, pad + body);
      blocked[index(cx, cy)] = outside || hitsColumn(s, x, y, body) ? 1 : 0;
    }
  }
  built.fill(-1);
}

/**
 * Волна Дейкстры от цели по всей сетке.
 *
 * Обычная очередь вместо приоритетной: весов всего два, и вставка в конец даёт
 * тот же результат при повторной релаксации соседей — а стоит она константу
 * вместо логарифма. На девятистах клетках разница между «дорого» и «незаметно».
 */
function buildField(s: SimState, player: number): void {
  const field = cost[player];
  field.fill(BLOCKED, 0, cols * rows);

  const startX = cellX(s.pX[player]);
  const startY = cellY(s.pY[player]);
  const start = index(startX, startY);
  // Цель внутри колонны — вырожденный случай (игрока туда вытолкнет физика),
  // но поле обязано остаться осмысленным, а не пустым.
  field[start] = 0;

  let head = 0;
  let tail = 0;
  queue[tail++] = start;

  while (head < tail) {
    const cur = queue[head++];
    const cx = cur % cols;
    const cy = (cur / cols) | 0;
    const base = field[cur];

    for (let d = 0; d < 8; d++) {
      const nx = cx + DX[d];
      const ny = cy + DY[d];
      if (nx < 0 || ny < 0 || nx >= cols || ny >= rows) continue;
      const ni = index(nx, ny);
      if (blocked[ni]) continue;

      // Диагональ сквозь угол двух стен не считается проходом: тело шире
      // точки, и враг там застрянет, а поле обещало ему дорогу.
      if (DX[d] !== 0 && DY[d] !== 0) {
        if (blocked[index(cx + DX[d], cy)] || blocked[index(cx, cy + DY[d])]) continue;
      }

      const next = base + (DX[d] !== 0 && DY[d] !== 0 ? DIAGONAL : STRAIGHT);
      if (next >= field[ni]) continue;
      field[ni] = next;
      queue[tail++] = ni;
    }
  }
  built[player] = s.tick;
}

/**
 * Подготовить навигацию к тику. Зовётся один раз из шага врагов.
 *
 * Сетка перестраивается при смене геометрии, поля — по расписанию. И то, и
 * другое дешевле, чем кажется, но дороже, чем ноль.
 */
export function updateNav(s: SimState): void {
  /*
   * Кэш обесценивается целиком, когда мир перестал быть тем же миром.
   *
   * Три признака, и каждый закрывает свою дыру. Смена объекта состояния — в
   * процессе их много, CI гоняет тысячи забегов подряд. Ход времени назад —
   * перезапуск забега. И метка восстановления: `loadSnapshot` подменяет мир
   * целиком, но прыжок ВПЕРЁД на срок короче периода пересчёта первые два
   * признака не видят вовсе, а поле при этом посчитано для другого момента.
   * Ровно на этом стоят лечение снимком большинства (0.9.0) и откаты (1.1).
   */
  if (owner !== s || s.tick < lastTick || s.navEpoch !== lastEpoch) {
    owner = s;
    lastEpoch = s.navEpoch;
    gridKey = -1;
    built.fill(-1);
  }
  lastTick = s.tick;

  /*
   * В ключ входит вся геометрия, а не только размер арены.
   *
   * Раскладка шаблона с отражением: до двенадцати шаблонов колонны были одной
   * константой, и размера с составом хватало — геометрия между комнатами не
   * менялась. Теперь меняется каждую комнату.
   *
   * И признак боссовой комнаты: на её арене колонн нет вовсе (GDD §8.1).
   * Без него сетка, построенная в восьмой комнате, доживала бы до боя с
   * боссом и врала бы непроходимыми пятнами посреди колеса.
   *
   * Ошибка в обоих случаях была бы ТИХОЙ: поле потока не входит ни в снимок,
   * ни в хеш, поэтому ни один golden-реплей её бы не поймал.
   */
  const boss = s.meta[Meta.Phase] === RunPhase.Boss ? 1 << 30 : 0;
  const key =
    s.arenaW ^
    (s.arenaH << 1) ^
    (s.playerCount << 3) ^
    (s.meta[Meta.Template] << 6) ^
    (s.meta[Meta.Flip] << 11) ^
    boss;
  if (key !== gridKey) {
    gridKey = key;
    buildGrid(s);
  }

  for (let p = 0; p < built.length; p++) {
    /*
     * Поле мёртвого не пересчитывается — и не имеет права читаться.
     *
     * Пока расписание просто пропускало погибшего, его последнее поле
     * оставалось в буфере навсегда: враг, не успевший сменить цель, шёл к
     * точке, где игрок был живым, и делал это тем увереннее, чем дольше тот
     * мёртв. Отметка «поля нет» закрывает вторую половину того же правила,
     * что и сброс кэша при восстановлении снимка: устаревшее поле не должно
     * быть читаемым.
     */
    if (p >= s.playerCount || (s.pFlags[p] & EntityFlag.Alive) === 0) {
      built[p] = -1;
      continue;
    }
    if (built[p] >= 0 && s.tick - built[p] < REBUILD_EVERY) continue;
    buildField(s, p);
  }
}

/**
 * Направление шага к игроку из точки — уже с обходом препятствий.
 *
 * Возвращается через модульные переменные, а не кортежем: зовётся для каждого
 * врага каждый тик, а ядру запрещено аллоцировать в горячем пути.
 *
 * Если поле недостижимо (враг в закутке или поле ещё не строилось), даётся
 * направление напрямую: хуже обхода, но лучше остановки.
 */
export let flowX: Fx = 0;
export let flowY: Fx = 0;

export function flowTo(_s: SimState, player: number, x: Fx, y: Fx): boolean {
  const field = cost[player];
  const cx = cellX(x);
  const cy = cellY(y);

  let bestX = 0;
  let bestY = 0;
  let best = field[index(cx, cy)];
  let found = false;

  for (let d = 0; d < 8; d++) {
    const nx = cx + DX[d];
    const ny = cy + DY[d];
    if (nx < 0 || ny < 0 || nx >= cols || ny >= rows) continue;
    const ni = index(nx, ny);
    if (blocked[ni]) continue;
    if (field[ni] >= best) continue;
    best = field[ni];
    bestX = DX[d];
    bestY = DY[d];
    found = true;
  }

  if (!found) {
    flowX = 0;
    flowY = 0;
    return false;
  }

  // Нормализуем восемь направлений сами: диагональ иначе быстрее прямой.
  const diag = bestX !== 0 && bestY !== 0;
  const unit = diag ? 46341 : 65536; // √2/2 и 1 в Q16.16
  flowX = bestX * unit;
  flowY = bestY * unit;
  return true;
}

/**
 * Есть ли прямая видимость между точками.
 *
 * Нужна тем, кто бьёт по прямой: стрелять или таранить сквозь колонну
 * бессмысленно, а игроку такой телеграф обещает атаку, которой не будет.
 * С 0.7.0 понадобится Лучу — он простреливает арену насквозь.
 */
export function lineOfSight(s: SimState, x0: Fx, y0: Fx, x1: Fx, y1: Fx, r: Fx): boolean {
  const dx = sub(x1, x0);
  const dy = sub(y1, y0);
  const steps = 12;
  for (let i = 1; i <= steps; i++) {
    const x = (x0 + (Math.trunc((dx * i) / steps) | 0)) | 0;
    const y = (y0 + (Math.trunc((dy * i) / steps) | 0)) | 0;
    if (hitsColumn(s, x, y, r)) return false;
  }
  return true;
}

/**
 * Точка позади цели относительно наблюдателя.
 *
 * Заготовка под Забрало (0.7.0): у него щит спереди, и брать его надо со
 * спины. Считается здесь, а не в самом враге, потому что «зайти за спину» —
 * задача навигации, а не автомата состояний: дойти до этой точки всё равно
 * придётся полем потока.
 */
export let flankX: Fx = 0;
export let flankY: Fx = 0;

export function flankPoint(
  s: SimState,
  target: number,
  facingX: Fx,
  facingY: Fx,
  distance: Fx,
): void {
  const back = distance / 65536;
  flankX = (s.pX[target] - (((facingX / 65536) * back * 65536) | 0)) | 0;
  flankY = (s.pY[target] - (((facingY / 65536) * back * 65536) | 0)) | 0;
}
