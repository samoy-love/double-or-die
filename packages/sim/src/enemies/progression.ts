/**
 * Продвижение по этажу: старт комнаты, зачистка, следующая дверь, конец этажа.
 *
 * Здесь же — расчёт прошлой комнаты и новая раскладка карт: пари живут внутри
 * боя и начинаются вместе с ним, отдельного экрана ставок нет (GDD §9.1).
 */

import { aceAtSettlement, dealCards, offerAceBet, resetAce, settleBets } from '../bets';
import {
  APPETITE_DEFAULT,
  ARENA_TEMPLATES,
  CURSE,
  FLIP_COUNT,
  FLOORS_PER_RUN,
  ROOMS_PER_FLOOR,
  ROOM_PAYOUT,
  UPGRADE,
  WAVE,
  roomGapTicksFor,
} from '../config';
import { offerDoors } from '../doors';
import { applyCurseEffects, enterHouseCut, expireCurse } from '../floor';
import { closeReward, openGift, openShop } from '../upgrades';
import { endRun } from '../run';
import { Stream, nextInt } from '../rng';
import { Curse, DoorType, EntityFlag, Meta, RunPhase, type SimState } from '../state';
import { bossRoomBudget, roomBudget } from './spawn';

/**
 * Начать комнату с первой волны.
 *
 * Здесь же — расчёт предыдущей и новая раскладка карт: пари живут внутри боя
 * и начинаются вместе с ним, отдельного экрана ставок нет (GDD §9.1).
 */
export function startRoom(s: SimState, room: number): void {
  /*
   * Порядок здесь несущий: Крупье, расчёт, раздача.
   *
   * Сначала сбрасывается Крупье — новая комната начинается с чистого бюджета
   * выходов и без чужого жеста. Потом он выходит принимать расчёт, и только
   * потом идёт сам расчёт: жесты, которые тот породит, попадают в уже стоящее
   * тело. Обратный порядок стоил дефекта — раздача, шедшая последней, стирала
   * присутствие и оставляла жест, а это запрещённое инвариантом состояние.
   */
  resetAce(s);
  aceAtSettlement(s);

  // Расчёт прошлой комнаты, но БЕЗ очистки слотов: пока идёт пауза, игрок
  // смотрит на результаты — выигранное золотится, проигранное показывает,
  // насколько не хватило. Слоты освобождаются, когда начинается бой.
  settleBets(s);

  // Дошёл до новой комнаты — серия смертей прервана, и Крупье снова можно
  // шутить: правило дозировки защищает от добивания, а не запрещает юмор.
  if (room > 1) s.meta[Meta.DeathStreak] = 0;

  /*
   * Аппетит сбрасывается только в первой комнате этажа.
   *
   * Раньше сброс стоял здесь безусловно, и это было верно: экрана двери не
   * существовало, защёлка в бою его заменяла, и «новая комната — новое
   * решение» означало «сбросить на старте комнаты». С приходом двери выбор
   * делается ДО комнаты, и тот же сброс стирал его в тот же тик — игрок
   * выбирал «По-крупному» и входил в бой со «Скромно».
   *
   * Теперь сброс живёт там, где открывается экран (`offerDoors`), а сюда
   * попадает только случай, у которого двери нет вовсе: первая комната этажа.
   */
  if (room === 1) s.pAppetite.fill(APPETITE_DEFAULT);

  /*
   * Новая комната — новая арена.
   *
   * Шаблон и его отражение берутся из потока `layout`, объявленного ещё в
   * 0.1.0 и до сих пор не работавшего: расстановка колонн была единственной
   * константой на всю игру. Отдельный поток обязателен — правка любой другой
   * системы иначе сдвинула бы раскладку арен, и дейли перестали бы
   * воспроизводиться между версиями (TECH §2.3).
   *
   * Два обращения, а не одно: шаблон и отражение — независимые решения, и
   * упаковка их в одно число `t * 4 + f` связала бы соседние шаблоны с
   * соседними отражениями на любом сдвиге потока.
   */
  s.meta[Meta.Template] = nextInt(s.rng, Stream.Layout, ARENA_TEMPLATES.length);
  s.meta[Meta.Flip] = nextInt(s.rng, Stream.Layout, FLIP_COUNT);

  /*
   * Тип комнаты приходит с выбранной двери.
   *
   * До первой двери (комната 1 каждого этажа) выбора не было — игрок только
   * что вошёл на этаж, — и комната обычная. Гарантия «Лавка не позже пятой»
   * считается по этому же полю, поэтому запоминать её надо здесь, а не на
   * экране двери: подтверждение и начало комнаты разнесены по тикам.
   */
  const pick = s.meta[Meta.DoorPick];
  s.meta[Meta.RoomType] = room > 1 && pick >= 0 ? s.doorType[pick] : DoorType.Fight;
  s.meta[Meta.DoorPick] = -1;
  if (s.meta[Meta.RoomType] === DoorType.Shop) s.meta[Meta.LastShopRoom] = room;
  if (room === 1) s.meta[Meta.LastShopRoom] = 0;

  // Проклятие живёт ровно одну комнату и снимается её прохождением (GDD §11):
  // долг забирает темп, а не деньги, и растянутый на этаж он забирал бы этаж.
  expireCurse(s);
  // Разовый эффект «Кровью» срабатывает ровно на входе в проклятую комнату,
  // а не каждый тик боя — остальные проклятия читают себя сами по ходу боя.
  applyCurseEffects(s);

  /*
   * Передышка на изломе бюджета угрозы (playtest 0.3.1, DIFFICULTY §4).
   *
   * Ровно там, где рост бюджета переходит с пологого участка на крутой
   * (`WAVE.roomGrowthKink`), живые получают два сердца — компенсация
   * ускорения, которое начинается в этой же комнате. Одного сердца не
   * хватило: читер-тест (100% точность/уклонение) всё ещё не доживал даже с
   * ним. Один раз за этаж: комната с этим номером встречается на каждом
   * этаже ровно однажды, повторного срабатывания в том же забеге нет по
   * построению.
   */
  if (room === WAVE.roomGrowthKink) {
    for (let p = 0; p < s.playerCount; p++) {
      if ((s.pFlags[p] & EntityFlag.Alive) === 0) continue;
      s.pHearts[p] = Math.min(UPGRADE.maxHearts, s.pHearts[p] + 2);
    }
  }

  s.meta[Meta.Room] = room;
  s.meta[Meta.Wave] = 0;
  s.meta[Meta.WaveBudget] = 0;
  s.meta[Meta.RoomStartTick] = s.tick;
  // Перед первой комнатой расчёта не было, и пять секунд экрана итогов
  // выродились бы в пять секунд пустоты. Развилка живёт в конфиге: её знает
  // ещё и пропуск расчёта.
  s.meta[Meta.NextWaveAt] = s.tick + roomGapTicksFor(room);

  // Бюджет комнаты целиком — знаменатель прогресса удержаний. Считается один
  // раз при входе: волны берут из него, а пари меряют по нему пройденный путь.
  // Жирный бой добавляет +50% (GDD §5) — та же добровольная сложность за
  // деньги, что и у пари, только на уровне всей комнаты.
  const budget = roomBudget(room, s.playerCount, s.meta[Meta.Floor]);
  s.meta[Meta.RoomThreat] =
    s.meta[Meta.RoomType] === DoorType.Fat ? Math.round(budget * 1.5) : budget;
  s.meta[Meta.ThreatCleared] = 0;
  dealCards(s);
  // И его собственная карта — раз в два-три боя (GDD §12А.1). Строго ПОСЛЕ
  // раздачи: та начинается с очистки арены и стёрла бы её тем же движением.
  offerAceBet(s);
}

/**
 * Базовая выплата за расчищенную комнату (ECONOMY §4) — второй источник
 * дохода рядом с дропом фишек. `min(тир, кошелёк)` не применяется: это не
 * ставка, а гарантированный доход, ради которого «сдавливание» (ECONOMY §6)
 * вообще сходится для осторожного игрока, не берущего пари.
 *
 * Кооп-множитель `0.5 + 0.5/N`, как и у доли заведения (ECONOMY §11), но
 * записан через целые числа: `(N+1)/(2N)` — то же значение без деления с
 * плавающей точкой.
 */
function payRoomClear(s: SimState): void {
  const amount = ROOM_PAYOUT.base + ROOM_PAYOUT.perFloor * (s.meta[Meta.Floor] - 1);
  const n = s.playerCount;
  let payout = Math.trunc((amount * (n + 1)) / (n * 2));
  // Комиссия (GDD §11): выплата за комнату урезана, пока проклятие активно.
  if (s.meta[Meta.Curse] === Curse.Commission && s.meta[Meta.CurseRoom] === 1) {
    payout = Math.trunc((payout * CURSE.commissionPayoutPct) / 100);
  }
  for (let p = 0; p < n; p++) {
    if ((s.pFlags[p] & EntityFlag.Alive) === 0) continue;
    s.pChips[p] += payout;
  }
}

/**
 * Комната зачищена: дальше следующая, босс, следующий этаж или конец забега.
 *
 * До 0.4.0 здесь стоял безусловный `startRoom(room + 1)`, и забег был
 * бесконечным счётчиком комнат: ни этажа, ни конца, ни победы. Ворота версии
 * требуют забега на 12–18 минут — то есть чего-то, что кончается.
 *
 * Босс стоит между восьмой комнатой и концом этажа (GDD §8.1), и шов с ним
 * здесь ровно один — признак «бой с боссом идёт». Сам бой живёт в `boss.ts`,
 * и импорта оттуда тут нет намеренно: волны зовут эту функцию, а босс зовёт
 * волны, — встречный импорт замкнул бы модули в цикл.
 */
export function advanceRoom(s: SimState): void {
  if (s.meta[Meta.Phase] === RunPhase.Summary) return;
  // Пока босс жив, комнату не кончает даже пустая арена: волны в боссовой
  // комнате идут наравне с ним, а конец ей ставит его смерть.
  if (s.meta[Meta.Phase] === RunPhase.Boss && s.meta[Meta.BossMaxHP] !== 0) return;

  payRoomClear(s);

  /*
   * Дверь «Лавка» обещала бой И магазин после него (GDD §5) — вот он.
   *
   * Второй раз сюда с тем же типом комнаты не попасть: из лавки выходят через
   * `leaveReward`, а он идёт в `nextRoom` мимо этой развилки, и следующий вход
   * случится уже после `startRoom`, который тип комнаты переназначит.
   */
  if (s.meta[Meta.RoomType] === DoorType.Shop) {
    openShop(s);
    return;
  }

  /*
   * Дверь «Дар» обещала бой И бесплатный апгрейд на выбор из трёх (GDD §5).
   *
   * Тот же прилавок и та же фаза, что у лавки: за Даром не стоит ни отдельного
   * экрана, ни отдельного состояния, потому что отличие у него ровно одно —
   * цена не берётся.
   *
   * Открыться Дар может отказаться: если все шесть апгрейдов уже у стола,
   * давать нечего, и прилавок, открытый пустым, обещал бы выбор из трёх и не
   * дал бы ни одного. Тогда комната кончается как обычный бой — забег идёт к
   * следующей двери, ничего не потеряв.
   */
  if (s.meta[Meta.RoomType] === DoorType.Gift && openGift(s)) return;

  nextRoom(s);
}

/**
 * Экран награды закрылся — забег идёт дальше ровно туда, куда шёл бы без него.
 *
 * Отдельно от `advanceRoom` по той же причине, что и `leaveFloor`: экран ждёт
 * игрока, и переход случается в тот тик, когда он ушёл, а не когда кончилась
 * комната.
 */
export function leaveReward(s: SimState): void {
  closeReward(s);
  s.meta[Meta.Phase] = RunPhase.Fight;
  nextRoom(s);
}

/** Что идёт после комнаты: следующая дверь, босс или расчёт с заведением. */
function nextRoom(s: SimState): void {
  if (s.meta[Meta.Room] < ROOMS_PER_FLOOR) {
    /*
     * Между комнатами встаёт экран двери, а не следующая комната сразу.
     *
     * Он ждёт игрока, а не часов, поэтому здесь только предложение: сама
     * комната начнётся, когда выбор подтвердят (`stepDoors` → `enterDoor`).
     */
    offerDoors(s);
    return;
  }
  if (s.meta[Meta.Phase] !== RunPhase.Boss) {
    // Восьмая комната кончилась — выходит босс. Комната остаётся восьмой: у
    // боссовой свой бюджет угрозы, половина восьмой (DIFFICULTY §8).
    s.meta[Meta.Phase] = RunPhase.Boss;
    startRoom(s, ROOMS_PER_FLOOR);
    s.meta[Meta.RoomThreat] = bossRoomBudget(s.meta[Meta.Floor], s.playerCount);
    return;
  }

  /*
   * Босс мёртв — заведение берёт своё, и только потом этаж кончается.
   *
   * Плата относится к ПРОЙДЕННОМУ этажу, поэтому считается до перехода: иначе
   * `20 × (F+1)²` посчиталось бы по номеру следующего, и первый этаж брал бы
   * плату второго. Победа на последнем этаже проходит через тот же экран —
   * рассчитаться с заведением обязан и победитель.
   */
  enterHouseCut(s);
}

/**
 * Плата внесена (или записана в долг) — этаж кончается.
 *
 * Отдельно от `advanceRoom` потому, что вызывается не оттуда: экран платы
 * ждёт игрока, и переход случается в тот тик, когда он ответил.
 */
export function leaveFloor(s: SimState): void {
  s.meta[Meta.Phase] = RunPhase.Fight;
  if (s.meta[Meta.Floor] < FLOORS_PER_RUN) {
    s.meta[Meta.Floor]++;
    startRoom(s, 1);
    return;
  }
  endRun(s, true);
}

/** Убрать с арены всё, кроме игроков: перезапуск забега и старт комнаты. */
export function clearArena(s: SimState): void {
  s.eActive.fill(0);
  s.bActive.fill(0);
  s.cActive.fill(0);
  s.spActive.fill(0);
  // Карты — тоже арена. Сценарий про подбор кладёт свою карту в известную
  // точку, и раскладка начала забега, оставшаяся лежать, превращает счёт
  // карт в счёт чужих карт.
  s.kActive.fill(0);
  // Шары и провалы колеса — тоже арена, и уезжают вместе с ней. Сектор,
  // оставшийся проваленным после боссовой комнаты, вырезал бы дыру в обычной,
  // где никакого колеса нет вовсе.
  s.ballActive.fill(0);
  s.sectorFallAt.fill(0);
  s.sectorRestoreAt.fill(0);
}
