/**
 * Забег как целое: чем он кончается и что игрок с собой уносит.
 *
 * Отдельный модуль, а не пара функций в `enemies.ts`, по причине зависимостей:
 * конец забега знают и волны (комнаты кончились), и бой (все умерли), и оба
 * лежат ниже по графу импортов. Модуль, который не тянет ни того, ни другого,
 * могут звать оба — а обратный порядок замкнул бы импорты в цикл, и обращения
 * к `Meta` в горячем пути перестали бы инлайниться (см. историю `navEpoch` в
 * `state.ts`).
 */

import { payAceOnRunEnd, progressOf } from './bets';
import { KEYS, MAX_ACTIVE_BETS } from './config';
import { BetState, Meta, RunPhase, type SimState } from './state';

/**
 * Ключи за забег: `1 за каждые 5 выполненных пари + 3 за побеждённого босса`
 * плюс `1 за каждые 100 непотраченных фишек` (ECONOMY §12).
 *
 * Конвертация непотраченных фишек — не украшение, а несущее правило: без неё
 * фишки после смерти ничего не стоят, и «Последняя сделка» в 0.6.0
 * превратится из пари в подарок, который правильно принимать всегда.
 *
 * Любой завершённый забег даёт минимум один ключ. Без этого пола смерть на
 * первом этаже с четырьмя выполненными пари давала бы ноль — арифметика
 * формулы, а не решение дизайна.
 */
export function keysEarned(s: SimState): number {
  let chips = 0;
  for (let i = 0; i < s.playerCount; i++) chips += s.pChips[i];

  const fromBets = Math.trunc(s.meta[Meta.BetsWon] / KEYS.betsPerKey);
  const fromChips = Math.trunc(chips / KEYS.chipsPerKey);
  const fromBosses = KEYS.perBoss * s.meta[Meta.BossesBeaten];

  return Math.max(KEYS.floor, fromBets + fromChips + fromBosses);
}

/**
 * Сколько строк займёт разбивка источников ключей на экране итогов.
 *
 * Раньше эта формула жила в двух местах сразу: `drawSummaryScreen`
 * (`renderer.ts`) рисовал разбивку, а `summaryBreakdownLines`
 * (`menuLayout.ts`) отдельно считала её высоту для хитбокса кнопки «Ещё
 * разок» — и рассинхрон этих двух копий уже был найден и исправлен как
 * отдельный дефект (кнопка наезжала на текст). `menuLayout.ts` зовёт именно
 * эту функцию для хитбокса. `drawSummaryScreen` (renderer.ts) по-прежнему
 * считает разбивку своим циклом — ему нужны не только длина, но и текст
 * каждой строки, а не только их число, — но сверяет число напечатанных
 * строк с этой функцией в dev-сборке (iter-5, ТЗ-18): расхождение формул
 * теперь ловится в консоли, а не только глазами на кадре.
 */
export function summaryLineCount(s: SimState): number {
  let chips = 0;
  for (let i = 0; i < s.playerCount; i++) chips += s.pChips[i];
  const fromBets = Math.trunc(s.meta[Meta.BetsWon] / KEYS.betsPerKey);
  const fromChips = Math.trunc(chips / KEYS.chipsPerKey);
  const fromBosses = KEYS.perBoss * s.meta[Meta.BossesBeaten];
  let lines = 0;
  if (s.meta[Meta.BetsWon] !== 0) lines++;
  if (chips !== 0) lines++;
  if (s.meta[Meta.BossesBeaten] !== 0) lines++;
  if (fromBets + fromChips + fromBosses < KEYS.floor) lines++;
  return lines;
}

/**
 * Кончить забег: победой или смертью.
 *
 * До 0.4.0 гибель всех игроков через три секунды вызывала `spawnPlayers` и
 * начинала забег заново прямо в симуляции. Это было честно для версии без
 * структуры — играть иначе было не во что, — но забег, который начинается
 * сначала, не имеет ни итогов, ни ключей, ни причины вернуться. Ворота версии
 * требуют, чтобы больше шестидесяти процентов плейтестеров начинали второй
 * забег ДОБРОВОЛЬНО; невозможно измерить добровольность того, что случается
 * само.
 *
 * «Последняя сделка» (GDD §12А.3) встанет между смертью и итогами в 0.6.0.
 * До неё смерть — это конец, и он обязан выглядеть концом.
 */
/**
 * Погасить всё, что летит и тлеет, входя в фазу без боя.
 *
 * Мир на экранах двери, платы, лавки и итогов замирает, а тик продолжает
 * идти — время на экране тоже время. Срок жизни снаряда и фишки записан
 * АБСОЛЮТНЫМ тиком, поэтому замороженный снаряд молча переживает свой срок:
 * шагать его некому, а часы идут. Инвариант «снаряд активен после истечения
 * срока» на этом и падал.
 *
 * Поймал дефект headless-прогон на шестидесяти тысячах тиков — один сид из
 * тридцати, тик 2411. На коротком прогоне он не виден вовсе: чтобы дожить до
 * экрана с пулей в воздухе, нужно сначала зачистить комнату, а боты
 * дочищают её редко.
 *
 * Чинится не смягчением инварианта — он прав, такого состояния быть не
 * должно, — а тем, что заморозка мира гасит и то, что в нём летело. Комната
 * при этом уже кончена: снаряды и фишки принадлежали ей, а не экрану.
 */
export function freezeArena(s: SimState): void {
  s.bActive.fill(0);
  s.cActive.fill(0);
}

export function endRun(s: SimState, victory: boolean): void {
  if (s.meta[Meta.Phase] === RunPhase.Summary) return;

  s.meta[Meta.Phase] = RunPhase.Summary;
  s.meta[Meta.PhaseUntil] = 0;
  s.meta[Meta.Victory] = victory ? 1 : 0;

  freezeArena(s);

  /*
   * Ставки Крупье он забирает ДО подсчёта ключей.
   *
   * Непотраченные фишки конвертируются в ключи (§12), а проигранная Ставка
   * Крупье — это фишки, которые игроку уже не принадлежат. Обратный порядок
   * выдавал бы ключи за деньги, ушедшие заведению в том же кадре.
   */
  payAceOnRunEnd(s);
  s.meta[Meta.Keys] = keysEarned(s);

  /*
   * Пари, застигнутые концом забега, разрешаются как проигранные.
   *
   * Не «остаются активными» и не «возвращают кон»: кон уже списан, а условие
   * не выполнено. Оставить их активными значило бы показать на экране итогов
   * пари, которое всё ещё чего-то ждёт от забега, которого больше нет.
   */
  for (let p = 0; p < s.playerCount; p++) {
    for (let n = 0; n < MAX_ACTIVE_BETS; n++) {
      const k = p * MAX_ACTIVE_BETS + n;
      if (s.aState[k] !== BetState.Active) continue;
      // Прогресс снимается ДО смены состояния, тем же приёмом, что и у
      // `loseBet` — иначе `nearMissOf` на экране итогов (ТЗ-13 iter-3) читал
      // бы `aNearMiss`, ни разу не записанный для пари, застигнутых концом
      // забега, а не проигрышем в бою.
      s.aNearMiss[k] = progressOf(s, p, n);
      s.aState[k] = BetState.Lost;
    }
  }
}
