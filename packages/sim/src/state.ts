/**
 * Чем Крупье занят, пока игрок воюет.
 *
 * Юмор играется телом: написанная шутка стареет с третьего забега и требует
 * перевода на семь языков, поведение — нет (GDD §17А). Поэтому жест —
 * сущность симуляции, а реплики поверх него приезжают отдельным словарём.
 *
 * Единственное перечисление ядра без `const`, и это не недосмотр. Жест —
 * единственное значение ядра, которое снаружи раскладывают по ключам:
 * словарь барок объявлен как `Record<AceGesture, …>`
 * (`packages/client/src/barks.ts`), то есть перечисление работает таблицей,
 * а не сравнением. Обычный `enum` оставляет объект в сборке, и таблица
 * переживает любой эмиттер — в том числе тот, что `const enum` стирает
 * подстановкой вместо того, чтобы оставить объект. Остальным перечислениям
 * ядра хватает сравнений, поэтому им `const` ничего не стоит.
 */
export enum AceGesture {
  None = 0,
  /** Скучает: игрок третью комнату не берёт карт. */
  Yawn = 1,
  /** Радуется провалу — подпрыгивает и хлопает. */
  Applaud = 2,
  /** Игрок вот-вот выиграет крупно: делает вид, что занят другим. */
  TurnAway = 3,
  /** Игрок в плюсе по сальдо: суетится и поправляет цилиндр. */
  Fidget = 4,
  /**
   * Соскочил на самом краю: молча показывает большой палец вниз.
   * Порог — `CARD.cashOutTellPct`, 90% по GDD §17А.
   */
  ThumbsDown = 5,
  /** Особенно нелепая смерть: аплодирует стоя. */
  Ovation = 6,
}

export interface SimState {
  /** Номер тика с начала забега. Основная единица времени — не секунды. */
  tick: number;
  seed: number;
  rng: RngState;
  /** Скаляры забега, см. `Meta`. */
  meta: Int32Array;

  /**
   * Размер арены. Производная от состава, а не отдельная степень свободы,
   * поэтому в хеш не входит: `playerCount` уже там, и разойтись они не могут.
   */
  arenaW: number;
  arenaH: number;

  /**
   * Сколько раз состояние подменяли восстановлением снимка.
   *
   * Не часть мира: в снимок и в хеш не входит, на поведение не влияет. Это
   * признак для тех, кто держит производные кэши — сегодня поле потока в
   * `nav.ts`, завтра всё, что появится вместе с откатами. Растёт монотонно,
   * поэтому сравнение с запомненным значением не может дать ложное совпадение.
   */
  navEpoch: number;

  // --- Игроки ---
  playerCount: number;
  pX: Int32Array;
  pY: Int32Array;
  pVX: Int32Array;
  pVY: Int32Array;
  pAimX: Int32Array;
  pAimY: Int32Array;
  pHearts: Int32Array;
  pFlags: Int32Array;
  /** Тик, до которого действует неуязвимость. */
  pInvulUntil: Int32Array;
  /** Тик, когда рывок снова доступен. */
  pDashReady: Int32Array;
  /** Тик окончания текущего рывка. */
  pDashUntil: Int32Array;
  /** Тик окончания кувырка после ударной волны. */
  pRagdollUntil: Int32Array;
  /** Накопленная доля выстрела в Q16.16: темп 6.5/с не кратен тику. */
  pShotAcc: Int32Array;
  pChips: Int32Array;
  /** Аппетит: индекс тира кона, выбранный до входа в комнату. */
  pAppetite: Int32Array;
  /**
   * Схема ввода игрока, см. `InputScheme` в каталоге пари.
   *
   * Живёт в состоянии, а не в клиенте, потому что от неё зависит РАСКЛАДКА:
   * пари, невыполнимое на схеме игрока, ему не выпадает (GDD §9.5). Всё, что
   * влияет на выдачу карт, обязано переигрываться вместе с боем и совпадать
   * у всех пиров.
   */
  pScheme: Int32Array;
  /**
   * Маска кнопок прошлого тика.
   *
   * Ставочные действия дискретны: карта подбирается подтверждением, а
   * «Забрать» от одного нажатия обязано срабатывать один раз, иначе удержание
   * кнопки сжигает все пари подряд. Фронт нажатия считается здесь, а не в
   * клиенте, потому что в реплее и в сети есть только эта маска.
   */
  pPrevButtons: Int32Array;

  /**
   * Купленные апгрейды: `MAX_UPGRADE_SLOTS` слотов на игрока.
   *
   * Индекс апгрейда в каталоге плюс единица; ноль — пустой слот. Сдвиг на
   * единицу нужен ровно затем, чтобы пустой слот отличался от нулевого
   * апгрейда: `fill(0)` — самый частый способ обнулить состояние, и первый
   * апгрейд каталога иначе оказывался бы у всех и всегда.
   */
  pUpgrades: Int32Array;

  // --- Двери и лавка ---
  /** Что предлагают три двери, см. `DoorType`. */
  doorType: Int32Array;
  /** Что лежит в лавке: индекс апгрейда плюс единица, ноль — слот пуст. */
  shopItem: Int32Array;
  /** Цена по формуле `база × 1.5^(F−1)`, посчитанная при раскладке. */
  shopPrice: Int32Array;

  // --- Босс: шары и секторы колеса ---
  ballX: Int32Array;
  ballY: Int32Array;
  /** Тик приземления: до него шар в воздухе, а сектор под ним размечен. */
  ballLandAt: Int32Array;
  /** Сектор, в который он сядет. Объявляется вместе с телеграфом. */
  ballSector: Int32Array;
  ballActive: Uint8Array;
  /** Тик, когда сектор провалится, и тик, когда вернётся. Ноль — цел. */
  sectorFallAt: Int32Array;
  sectorRestoreAt: Int32Array;

  // --- Карты пари на арене ---
  /** Карта — сущность симуляции: место, категория, владелец, срок. */
  kX: Int32Array;
  kY: Int32Array;
  /** Индекс пари в каталоге BETS. */
  kBet: Int32Array;
  /** Владелец: 0..3 — персональная, −1 — общая. */
  kOwner: Int32Array;
  kDeadline: Int32Array;
  kActive: Uint8Array;

  // --- Активные пари: MAX_ACTIVE_BETS на игрока ---
  /** Индекс пари в каталоге. */
  aBet: Int32Array;
  /** Поставленный кон. */
  aStake: Int32Array;
  /** Состояние, см. `BetState`. */
  aState: Int32Array;
  /** Счётчик для счётчиковых пари. */
  aCounter: Int32Array;
  /** Тик взятия: от него считается прогресс темповых. */
  aTakenAt: Int32Array;
  /** Снимок зачищенной угрозы на момент взятия: прогресс считается от него. */
  aThreatAt: Int32Array;
  /**
   * Насколько близко было к победе в момент срыва, `q` в Q16.16.
   *
   * Near-miss обязателен (GDD §9.3): «не хватило четырёх секунд» — главный
   * двигатель «ещё разок». Считать его на экране расчёта поздно, прогресс к
   * тому времени уже не восстановить, поэтому он снимается в момент провала.
   */
  aNearMiss: Int32Array;

  // --- Снаряды ---
  bX: Int32Array;
  bY: Int32Array;
  bVX: Int32Array;
  bVY: Int32Array;
  /** Тик, на котором снаряд исчезает. */
  bDeadline: Int32Array;
  /** Индекс владельца: 0..3 игрок, −1 враг. */
  bOwner: Int32Array;
  bActive: Uint8Array;

  // --- Враги ---
  eX: Int32Array;
  eY: Int32Array;
  eVX: Int32Array;
  eVY: Int32Array;
  eHP: Int32Array;
  eType: Int32Array;
  /** Состояние автомата врага, см. `EnemyPhase`. */
  ePhase: Int32Array;
  /** Тик перехода в следующее состояние. */
  ePhaseUntil: Int32Array;
  eTarget: Int32Array;
  /** Тик, на котором цель разрешено пересмотреть: память о цели 2 с. */
  eTargetUntil: Int32Array;
  /** Зафиксированное направление атаки: Клин в рывке не наводится. */
  eDirX: Int32Array;
  eDirY: Int32Array;
  eFlags: Int32Array;
  eActive: Uint8Array;

  // --- Отложенные спавны ---
  /** Метка на полу: где и когда появится враг. */
  spX: Int32Array;
  spY: Int32Array;
  spType: Int32Array;
  spAt: Int32Array;
  spActive: Uint8Array;

  // --- Фишки ---
  cX: Int32Array;
  cY: Int32Array;
  cVX: Int32Array;
  cVY: Int32Array;
  cValue: Int32Array;
  cDeadline: Int32Array;
  cActive: Uint8Array;

  /**
   * Все буферы состояния одним списком — для снимка и хеша одним проходом.
   *
   * Список строится ОДИН раз при создании состояния и живёт вместе с ним.
   * Собирать его на каждом вызове означало бы аллокацию из тридцати ссылок
   * в хеше, снимке и восстановлении — то есть ровно на пути отката и
   * сетевой сверки, где аллокаций быть не должно. Сами буферы не
   * пересоздаются никогда, поэтому список верен всё время жизни состояния.
   */
  views: readonly (Int32Array | Uint8Array)[];
}

