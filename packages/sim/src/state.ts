/** Снимок состояния. Предаллоцируется один раз и переиспользуется. */
export interface Snapshot {
  tick: number;
  seed: number;
  playerCount: number;
  data: (Int32Array | Uint8Array)[];
}

export function createSnapshot(s: SimState): Snapshot {
  return {
    tick: 0,
    seed: s.seed,
    playerCount: s.playerCount,
    data: s.views.map((buf) =>
      buf instanceof Uint8Array ? new Uint8Array(buf.length) : new Int32Array(buf.length),
    ),
  };
}

export function saveSnapshot(s: SimState, snap: Snapshot): void {
  snap.tick = s.tick;
  snap.seed = s.seed;
  snap.playerCount = s.playerCount;
  const src = s.views;
  for (let i = 0; i < src.length; i++) snap.data[i].set(src[i] as never);
}

/**
 * Восстановить состояние из снимка.
 *
 * Вместе с состоянием обязан выбрасываться и кэш навигации: поле потока
 * посчитано для другого момента времени, в состояние оно не входит и в хеш не
 * попадает, поэтому починить его нечему. Сам `updateNav` замечает только ход
 * времени НАЗАД, а восстановление бывает и вперёд — так работают лечение
 * снимком большинства (TECH §7.4) и откат, — и прыжок короче
 * `NAV.rebuildEvery` расписание пересчёта не видит вовсе.
 */
export function loadSnapshot(s: SimState, snap: Snapshot): void {
  s.tick = snap.tick;
  s.seed = snap.seed;
  s.playerCount = snap.playerCount;
  const dst = s.views;
  for (let i = 0; i < dst.length; i++) dst[i].set(snap.data[i] as never);
  /*
   * Метка восстановления, по которой навигация сбрасывает свой кэш.
   *
   * Счётчик, а не прямой вызов сброса, и это не стилистика. Импорт из `nav.ts`
   * замкнул бы модули в цикл `state → nav → state`, а циклический импорт
   * сборщик разрешает через геттеры пространства имён: обращения к `Meta` в
   * горячем пути перестают инлайниться, и тик боя начинает аллоцировать.
   * Замер поймал это сразу — 85 байт на тик против потолка в 64, — но найти
   * причину по симптому было бы почти невозможно: лишний импорт не выглядит
   * правкой производительности.
   *
   * Счётчик решает и более общую задачу. `updateNav` сам замечает смену
   * состояния и ход времени НАЗАД, но восстановление бывает и вперёд, а
   * прыжок короче периода пересчёта расписание не видит вовсе. Метка не
   * входит ни в снимок, ни в хеш: это не часть мира, а признак того, что мир
   * подменили.
   */
  s.navEpoch++;
}

/**
 * Хеш состояния, FNV-1a по всем буферам.
 *
 * Сверяется между пирами каждые 30 тиков и между операционными системами в CI.
 * Расхождение означает слом детерминизма — самый опасный класс багов здесь.
 */
export function hashState(s: SimState): number {
  let h = 0x811c9dc5;
  h = (Math.imul(h ^ s.tick, 0x01000193) >>> 0) >>> 0;
  h = (Math.imul(h ^ s.playerCount, 0x01000193) >>> 0) >>> 0;

  for (const buf of s.views) {
    if (buf instanceof Uint8Array) {
      for (let i = 0; i < buf.length; i++) h = Math.imul(h ^ buf[i], 0x01000193) >>> 0;
    } else {
      for (let i = 0; i < buf.length; i++) {
        const v = buf[i];
        h = Math.imul(h ^ (v & 0xff), 0x01000193) >>> 0;
        h = Math.imul(h ^ ((v >>> 8) & 0xff), 0x01000193) >>> 0;
        h = Math.imul(h ^ ((v >>> 16) & 0xff), 0x01000193) >>> 0;
        h = Math.imul(h ^ ((v >>> 24) & 0xff), 0x01000193) >>> 0;
      }
    }
  }
  return h >>> 0;
}

export const hashHex = (s: SimState): string => '0x' + hashState(s).toString(16).padStart(8, '0');

