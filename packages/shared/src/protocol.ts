/**
 * Версия формата ввода и сети.
 *
 * Растёт вместе с битовой маской `InputFrame`: любое новое действие обязано
 * попасть в маску, иначе оно не существует ни для реплея, ни для сети. Смена
 * делает старые реплеи и старых клиентов несовместимыми ЯВНО — понятным
 * сообщением при рукопожатии, а не десинком на тридцатой секунде.
 *
 * 3 — экранные действия заняли биты 16–19: навигация влево и вправо,
 *     подтверждение и отказ. Маска перестала быть шестнадцатибитной. Своими
 *     битами, а не переиспользованными боевыми: иначе смысл бита начинает
 *     зависеть от фазы забега, и кадр перестаёт читаться сам по себе.
 *     Расширение обошлось без потерь — кадр и раньше пакетировался пятью
 *     32-битными словами, а шестнадцать было границей СЕТЕВОЙ упаковки, до
 *     которой ещё две версии.
 * 2 — схема ввода заняла биты 14–15. Она едет кадром, а не настройкой
 *     клиента: игрок берётся за геймпад посреди забега, и реплей обязан
 *     переиграть в том числе это. От неё зависит, какие пари ему вообще
 *     предлагаются (матрица «пари × схема», GDD §9.5), то есть маска влияет
 *     на раскладку — старый лог в новом мире дал бы другие карты.
 * 1 — маска из TECH §6: огонь, рывок, подбор, «Забрать», рассмотреть,
 *     принять, отказаться, воскресить, аппетит, пинг, эмоции.
 *
 * Маска занимает двадцать бит из тридцати двух, свободны 20–31. Формата
 * реплея расширение не коснулось вовсе — кадр и раньше пакетировался пятью
 * 32-битными словами, и `buttons` занимал целое слово. Ограничением были
 * шесть байт СЕТЕВОЙ полезной нагрузки из TECH §7.5, и платить по этому счёту
 * придётся в 0.9.0, когда появится сеть: либо кадр вырастет на два байта,
 * либо экранные биты уедут в отдельный редкий пакет — в бою они всё равно
 * нули. Ставки Духа и самовоскрешение из 0.5.0 (GDD §14) помещаются в
 * оставшиеся двенадцать без нового расширения.
 */
export const PROTOCOL_VERSION = 3;

