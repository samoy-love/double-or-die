/**
 * Игровые события: общий словарь клиента, инструментов и будущей телеметрии.
 *
 * События ВЫВОДЯТСЯ из состояния, а не эмитятся симуляцией. Причина одна и
 * важная: ядру запрещено аллоцировать в горячем пути, а список событий — это
 * объекты и строки. Здесь только их форма, чтобы наблюдатель в клиенте и
 * приёмник телеметрии на сервере не разошлись в именах.
 */

/** Что случилось. Имена совпадают с хуками детекции пари из GDD §9.5. */
export type SimEventName =
  | 'run_start'
  | 'dash'
  | 'hurt'
  | 'death'
  | 'invulnerable_end'
  | 'bet_taken'
  | 'bet_won'
  | 'bet_lost'
  | 'bet_cashed';

export interface SimEvent {
  tick: number;
  name: SimEventName;
  player: number;
  /** Значение, ради которого событие и заводилось: сердца, кон, выплата. */
  value?: number;
  /** Идентификатор пари для ставочных событий. */
  bet?: string;
}
