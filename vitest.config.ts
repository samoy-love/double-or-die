import { defineConfig } from 'vitest/config';
import { aliases } from './vite.config.ts';

export default defineConfig({
  // Те же псевдонимы пакетов, что у сборки. Список один: разъехавшись, они
  // дали бы зелёный прогон при сломанной сборке — худший из возможных исходов.
  resolve: { alias: aliases },
  test: {
    globals: true,
    environment: 'node',
    include: ['tests/**/*.test.ts'],
    // Ядро обязано не аллоцировать в горячем пути, а проверить это без
    // принудительной сборки мусора нельзя: куча растёт и опадает сама, и
    // замер получился бы зелёным при любом коде.
    //
    // В Vitest 4 настройки пула переехали на верхний уровень. Пропустить эту
    // правку было бы дороже, чем кажется: тесты аллокаций пропускаются, когда
    // `gc` недоступен, — то есть набор остался бы зелёным, молча перестав
    // проверять главное правило ядра.
    pool: 'forks',
    execArgv: ['--expose-gc'],
    // Детерминизм проверяется в том числе повторяемостью самих тестов:
    // случайный порядок здесь только мешает читать падения.
    sequence: { shuffle: false },
    coverage: {
      provider: 'v8',
      // lcov — для Codecov, text — чтобы цифру было видно прямо в логе
      // прогона и за ней не приходилось идти на сайт.
      reporter: ['text', 'lcov'],
      // `include` здесь принципиально. Без него в отчёт попадают только
      // файлы, которые тест хоть раз импортировал, и модуль, не покрытый
      // вовсе, просто исчезает из знаменателя — покрытие растёт оттого, что
      // тестов стало меньше. С ним непокрытый модуль честно показывает 0%.
      // (В Vitest 3 это же включал отдельный флаг `all`, которого больше нет.)
      include: ['packages/**/*.ts'],
      exclude: [
        '**/*.d.ts',
        '**/*.test.ts',
        // Инструменты и генераторы: их «покрытие» ничего не говорит о том,
        // работает ли игра.
        'packages/tools/**',
      ],
    },
  },
});
