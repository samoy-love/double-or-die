import { defineConfig } from 'vitest/config';
import { aliases } from './vite.config.ts';

/** Прогон идёт под покрытием: `vitest run --coverage`. */
const withCoverage = process.argv.includes('--coverage');

export default defineConfig({
  // Те же псевдонимы пакетов, что у сборки. Список один: разъехавшись, они
  // дали бы зелёный прогон при сломанной сборке — худший из возможных исходов.
  resolve: { alias: aliases },
  test: {
    globals: true,
    environment: 'node',
    /*
     * Под покрытием прогон другой, и это не каприз.
     *
     * Инструментация V8 сама аллоцирует на каждый вызов и замедляет код в
     * разы. Замер «тик боя не аллоцирует» в таком прогоне меряет счётчики
     * покрытия, а не игру: 520 байт на тик против шестидесяти четырёх — это
     * цена инструментации, и «починить» её нечем. Держать заведомо красный
     * гейт нельзя: его перестают читать целиком, вместе с настоящими
     * падениями.
     *
     * Остальные тесты остаются, но с потолком времени в пять раз выше: под
     * инструментацией длинный прогон волн не укладывается в пять секунд, и
     * это тоже свойство замера, а не игры.
     */
    include: ['tests/**/*.test.ts'],
    /*
     * Калибровочный гейт (`tests/abstract-calibration-*.test.ts`) не входит
     * в `npm test` по умолчанию: 200 забегов на профиль — минимум, ниже
     * которого шум редких событий валит даже верную модель (см. шапку
     * `abstract-calibration-novice-single.test.ts`), а не число, которое
     * можно урезать ради скорости. Урезать нельзя, а вот дублировать в
     * каждом прогоне `npm test` — можно перестать: файлы дают 5.6с → 113с, и
     * это умножается на три ОС матрицы `determinism` (DEVLOOP §6А). Тот же
     * гейт, тем же объёмом, гоняется отдельно — `npm run test:calibration`
     * — своим шагом CI, один раз, а не трижды заодно с юнитами и golden.
     */
    exclude: ['tests/abstract-calibration-*.test.ts'],
    // Замер аллокаций под покрытием исключается списком, а не отрицанием
    // внутри `include`: отрицание там выбирает тесты как надо, но молча
    // обнуляет сам отчёт покрытия — «0/0 строк» вместо цифры.
    ...(withCoverage
      ? {
          exclude: ['tests/allocations.test.ts', 'tests/abstract-calibration-*.test.ts'],
          testTimeout: 25_000,
          hookTimeout: 25_000,
        }
      : {}),
    // Ядро обязано не аллоцировать в горячем пути, а проверить это без
    // принудительной сборки мусора нельзя: куча растёт и опадает сама, и
    // замер получился бы зелёным при любом коде.
    //
    // В Vitest 4 настройки пула переехали на верхний уровень. Пропустить эту
    // правку было бы дороже, чем кажется: тесты аллокаций пропускаются, когда
    // `gc` недоступен, — то есть набор остался бы зелёным, молча перестав
    // проверять главное правило ядра.
    pool: 'forks',
    execArgv: ['--expose-gc'],
    // Детерминизм проверяется в том числе повторяемостью самих тестов:
    // случайный порядок здесь только мешает читать падения.
    sequence: { shuffle: false },
    coverage: {
      provider: 'v8',
      // lcov — для Codecov, text — чтобы цифру было видно прямо в логе
      // прогона и за ней не приходилось идти на сайт.
      reporter: ['text', 'lcov'],
      // `include` здесь принципиально. Без него в отчёт попадают только
      // файлы, которые тест хоть раз импортировал, и модуль, не покрытый
      // вовсе, просто исчезает из знаменателя — покрытие растёт оттого, что
      // тестов стало меньше. С ним непокрытый модуль честно показывает 0%.
      // (В Vitest 3 это же включал отдельный флаг `all`, которого больше нет.)
      include: ['packages/**/*.ts'],
      exclude: [
        '**/*.d.ts',
        '**/*.test.ts',
        // Инструменты и генераторы: их «покрытие» ничего не говорит о том,
        // работает ли игра.
        'packages/tools/**',
      ],
    },
  },
});
