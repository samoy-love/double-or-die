import { defineConfig, devices } from '@playwright/test';

/**
 * Сквозные проверки: то, что не видно ни headless-раннеру, ни юнит-тестам.
 *
 * Ядро проверяется без графики и проверяется хорошо, но между «симуляция
 * считает верно» и «игра работает» остаётся дыра ровно в рендер: WebGL2 не
 * инициализировался, шейдер не собрался, канвас нулевого размера — во всех
 * этих случаях симуляция по-прежнему честно тикает, а на экране ничего нет.
 *
 * Два прогона по разным сборкам, и это принципиально:
 *
 *   — **дым идёт по ПРОДАКШЕН-сборке.** Проверять надо то, что уедет
 *     игрокам, а не то, что удобно проверять. Заодно здесь же доказывается,
 *     что отладочного интерфейса в релизе нет, — функционально, а не поиском
 *     строки в бандле.
 *   — **бенч рендера идёт по DEV-сборке.** Нагрузить сцену двумя тысячами
 *     частиц можно только через `__DOD__.stress()`, а его в релизе нет по
 *     той же причине, по которой он там не нужен.
 */

/**
 * Порты — СВОИ У КАЖДОГО ЧЕКАУТА, а не общие два числа.
 *
 * Причина не в удобстве, а в молчаливом отказе, который стоил вечера. Сервер
 * поднимается с `reuseExistingServer`, и на занятом порту Playwright не падает,
 * а берёт то, что там уже слушает. Пока чекаут один, это ускорение; как только
 * рядом появляется второй — worktree агента, вторая ветка, забытый вчерашний
 * `npm run e2e`, — тесты идут по ЧУЖОЙ сборке. Выглядит это как настоящее
 * падение своей: экран, который «не рисуется», отладочный метод, которого «нет»,
 * меню, которое «не держит забег». Ни одно из этого не про код, который правили.
 *
 * Порт считается из пути чекаута, поэтому у каждой копии он свой и переживает
 * перезапуск: соседи не спорят, а `reuseExistingServer` продолжает экономить
 * время внутри своей копии. В CI чекаут один, и хеш там просто постоянная.
 */
const checkout = [...import.meta.dirname].reduce(
  (h, c) => (Math.imul(h, 31) + c.charCodeAt(0)) | 0,
  7,
);
const offset = Math.abs(checkout) % 200;
/** Прод-превью. Диапазон свой, чтобы не спорить с `npm run dev`. */
const PROD_PORT = 4400 + offset;
/** Dev-сервер для бенча. Тоже свой: 5173–5176 заняты соседними проектами. */
const DEV_PORT = 5400 + offset;

/**
 * Бенч и визуальная регрессия идут по dev-сборке: обе опираются на
 * `__DOD__`, которого в релизе нет и быть не должно.
 */
const PERF = /(perf|visual)\.spec\.ts$/;

export default defineConfig({
  testDir: './e2e',
  forbidOnly: !!process.env.CI,
  /*
   * Ретраи и раздутые таймауты здесь были и не помогли: джоба `e2e` в CI
   * ограничена 15 минутами (`.github/workflows/ci.yml`), а весь набор в
   * норме укладывается в ~1m21s. Три полных попытки по 3 минуты добивают до
   * потолка ДО того, как Playwright успевает честно сообщить о падении —
   * джобу убивает GitHub, а не тест. Симптом («канвас не появился» ни разу
   * за несколько минут) — это зависание первого рендера под CI, не гонка
   * прогрева, и лишнее время его не лечит.
   */
  retries: 0,
  // Замер производительности не делят с соседями: чужой воркер на том же
  // ядре превращает бенч в замер загрузки машины.
  workers: 1,
  reporter: process.env.CI ? [['github'], ['list']] : 'list',
  timeout: 90_000,
  expect: { timeout: 15_000 },

  use: {
    trace: 'retain-on-failure',
    launchOptions: {
      args: [
        // Софтверный WebGL на раннере без видеокарты — норма, и отключать
        // его нельзя: без него игра не запустится вовсе и дым станет
        // бесполезным.
        '--use-gl=swiftshader',
        '--enable-unsafe-swiftshader',
        /*
         * Оба флага — известная причина того, что Chromium молча зависает
         * или падает под CI, а не открывает страницу вовсе: сервер отвечает
         * (см. `[WebServer]` в логе), а браузер трижды подряд не доходит до
         * первого кадра за 3 минуты. Раннер работает от root (см. шаг
         * установки зависимостей), а песочница Chrome от root по умолчанию
         * отказывается стартовать без `--no-sandbox`; `/dev/shm` в
         * контейнерах CI обычно урезан до 64 МБ, и рендерер, попытавшийся
         * взять из него разделяемую память, зависает, а не падает с
         * понятной ошибкой — отсюда и «канвас не появился» вместо
         * настоящего сообщения.
         */
        '--no-sandbox',
        '--disable-dev-shm-usage',
      ],
    },
  },

  projects: [
    {
      name: 'релиз',
      use: { ...devices['Desktop Chrome'], baseURL: `http://127.0.0.1:${PROD_PORT}` },
      testIgnore: PERF,
    },
    {
      name: 'бенч рендера',
      use: { ...devices['Desktop Chrome'], baseURL: `http://127.0.0.1:${DEV_PORT}` },
      testMatch: PERF,
    },
  ],

  /*
   * Вывод серверов — в лог, а не молча в никуда.
   *
   * По умолчанию Playwright копит stdout/stderr `webServer` и печатает его
   * только при ПАДЕНИИ САМОГО СЕРВЕРА — а не при падении теста, который к
   * нему стучится. Прогон CI падал на «канвас не появился» четыре раза
   * подряд без единой строки о том, что в это время делал сам сервер:
   * поднялся ли `vite preview`, успел ли добраться `npm run build`. Без
   * этого следующая красная сборка снова окажется гаданием по симптому.
   */
  webServer: [
    {
      command: `npm run build && npm run preview -- --port ${PROD_PORT} --host 127.0.0.1 --strictPort`,
      url: `http://127.0.0.1:${PROD_PORT}/`,
      reuseExistingServer: !process.env.CI,
      timeout: 120_000,
      stdout: 'pipe',
      stderr: 'pipe',
    },
    {
      command: `npm run dev -- --port ${DEV_PORT} --host 127.0.0.1 --strictPort`,
      url: `http://127.0.0.1:${DEV_PORT}/`,
      reuseExistingServer: !process.env.CI,
      timeout: 120_000,
      stdout: 'pipe',
      stderr: 'pipe',
    },
  ],
});
