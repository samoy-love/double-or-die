/**
 * Калибровка абстрактной модели против полной симуляции (SIMULATION.md §2),
 * профиль `novice:single` — нижняя граница навыка.
 *
 * Один профиль — один файл, и это не дробление ради дробления. `vitest`
 * (`pool: 'forks'`, vitest.config.ts) параллелит РАЗНЫЕ файлы по отдельным
 * процессам, но тесты ВНУТРИ одного файла остаются последовательными —
 * `collectFullSimMetrics` синхронный и CPU-bound, `it.concurrent` тут не
 * ускорил бы ничего. Раньше все 4 профиля жили в одном файле и считались
 * друг за другом — 97-165 секунд на прогон вместо 20-40 при том же объёме
 * выборки. Четыре файла — тот же гейт, посчитанный параллельно.
 *
 * Модель ускоряет поиск оптимума в тысячу раз ценой точности — и цена честна
 * только пока измерена. Расхождение больше 10% по любой из ключевых величин
 * означает, что абстракция врёт, и результатам поиска, построенным на ней,
 * доверять нельзя (SIMULATION §2, дословно).
 *
 * **Объём выборки — 200 забегов на профиль, и меньше нельзя.** Проверено
 * прямым замером (см. историю задачи): при 40-150 забегах даже ПРАВИЛЬНО
 * откалиброванная модель регулярно валит гейт — не потому что модель врёт, а
 * потому что редкие события (доля выигранных пари у слабого профиля,
 * `betWin`) на таких объёмах сами гуляют на 15-100% между соседними
 * прогонами. 200 — минимум, на котором шум точки сравнения падает ниже
 * 10-процентного порога теста; это НЕ «стабильная медиана с запасом», это
 * минимально достаточный объём для самого теста, дальше урезать некуда.
 * Расширенный ночной прогон по всем 16 профилям на объёме, приближающемся к
 * 50 000 суммарно (SIMULATION §2), делает отдельный скрипт калибровки, не
 * этот файл — здесь только проверка, что действующая `CalibrationParams` не
 * разошлась с полной симуляцией.
 */
import { describe, it } from 'vitest';
import { runCalibrationGate, THRESHOLD } from './helpers/calibration-gate';

describe('калибровка абстрактной модели (SIMULATION §2)', () => {
  it(
    `novice:single — расхождение с полной симуляцией не больше ${THRESHOLD * 100}%`,
    () => {
      runCalibrationGate('novice', 'single');
    },
    60_000,
  );
});
