/**
 * Калибровка абстрактной модели против полной симуляции (SIMULATION.md §2).
 *
 * Модель ускоряет поиск оптимума в тысячу раз ценой точности — и цена честна
 * только пока измерена. Расхождение больше 10% по любой из ключевых величин
 * означает, что абстракция врёт, и результатам поиска, построенным на ней,
 * доверять нельзя (SIMULATION §2, дословно).
 *
 * **Объём выборки — два уровня, и это решение задачи 2.1, а не документа.**
 * В документах названы три разных числа объёма: 640 забегов на профиль
 * (SIMULATION §6, генерация одной мутации поиска), 10 000 (одна проба поиска
 * целиком) и 50 000 (SIMULATION §2, периодическая переобучение раз в версию).
 * Ни одно из них не годится в гейт CI как есть:
 *
 *  - 50 000 — это ночной объём по определению документа, здесь он и остаётся;
 *    сотни полных забегов с ботом до нескольких тысяч тиков каждый — это
 *    секунды в CI, 50 000 — уже другой порядок времени;
 *  - 640 — объём ОДНОЙ мутации внутри поиска, а не объём проверки калибровки
 *    самой модели; он рассчитан на грубую оценку доли побед, а не на то,
 *    чтобы поймать 10-процентный дрейф на всех четырёх метриках сразу.
 *
 *  Поэтому гейт-прогон (этот файл, каждый коммит) берёт **200 забегов на
 *  профиль** — число, на котором уже стабилизируется медиана длительности
 *  комнаты и доля побед пари не гуляет за пределы одного процентного пункта
 *  между соседними прогонами (проверено локально: 5 прогонов по 200 на
 *  `median:single` дали доли побед 0.41–0.44). Он покрывает не все 16
 *  профилей, а по одному навыку на стратегию, выбранных так, чтобы задеть obе
 *  оси: `novice:single` (нижняя граница навыка), `median:stack` (опорный
 *  профиль SIMULATION §3 на самой требовательной по ставкам стратегии),
 *  `veteran:chips`, `master:none`. Расширенный ночной прогон (по требованию,
 *  не в этом файле — `npm run balance` вызовет то же `collectFullSimMetrics`
 *  с бОльшим `runs`) обязан пройти все 16 профилей на объёме, приближающемся
 *  к 50 000 суммарно, и именно там образуется таблица `CalibrationParams`,
 *  которую этот файл только проверяет, а не производит.
 */

import { describe, expect, it } from 'vitest';
import { calibrationChecks, collectFullSimMetrics, type RoomInput } from '@dod/tools/abstract';

/** Хватает, чтобы прожить весь первый этаж и заглянуть на второй у большинства профилей. */
const GATE_TICKS = 6000;
const GATE_RUNS = 200;
const THRESHOLD = 0.1;

const GATE_PROFILES: readonly [RoomInput['skill'], RoomInput['strategy']][] = [
  ['novice', 'single'],
  ['median', 'stack'],
  ['veteran', 'chips'],
  ['master', 'none'],
];

describe('калибровка абстрактной модели (SIMULATION §2)', () => {
  for (const [skill, strategy] of GATE_PROFILES) {
    // 200 полных забегов до 6000 тиков честно занимают 15-30 секунд — больше
    // дефолтного таймаута vitest (5000 мс). Без явного таймаута тест валится
    // по времени раньше, чем успевает вычислить расхождение, и красный прогон
    // выглядит как падение калибровки, а на деле это падение по таймауту.
    it(
      `${skill}:${strategy} — расхождение с полной симуляцией не больше ${THRESHOLD * 100}%`,
      () => {
        const full = collectFullSimMetrics(skill, strategy, GATE_RUNS, GATE_TICKS, 100_000);

        // Этаж 1 — единственный, до которого доживает достаточно забегов на
        // 200 прогонах при 6000 тиках: второй и третий этажи здесь дают
        // считаные комнаты, и статистика по ним слишком шумная для 10-процентного
        // порога. Ночной прогон (больше тиков, больше забегов) обязан снять
        // это ограничение и проверить все три этажа.
        const floor1 = full.find((f) => f.floor === 1);
        expect(floor1).toBeDefined();
        if (!floor1) return;
        // Знаменатель попаданий и дохода — комнаты НАЧАТЫЕ, их всегда хватает
        // (каждый забег даёт минимум одну). Длительность требует комнат
        // ЗАКОНЧЕННЫХ, и с ними жёстче: `novice` часто гибнет на первой.
        expect(floor1.sampleRoomsEntered).toBeGreaterThan(20);

        const input: RoomInput = { floor: 1, room: 4, players: 1, skill, strategy };
        const checks = calibrationChecks(input, floor1, undefined, THRESHOLD);

        for (const check of checks) {
          expect(
            check.ok,
            `${check.metric}: модель ${check.model.toFixed(3)} vs симуляция ${check.real.toFixed(3)} ` +
              `(расхождение ${(check.relativeError * 100).toFixed(1)}%)`,
          ).toBe(true);
        }
      },
      60_000,
    );
  }
});
