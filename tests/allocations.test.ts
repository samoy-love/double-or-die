/**
 * Ноль аллокаций в горячем пути.
 *
 * Правило ядра, которое невозможно соблюсти «по памяти»: один забытый литерал
 * объекта или массива внутри тика — и сборщик мусора приходит посреди боя. На
 * глаз это случайные микрофризы раз в несколько секунд, и ищут их долго,
 * потому что проявляются они не там, где написаны.
 *
 * Ловится этим тестом не только литерал. Дробное число, лежащее в переменной
 * МОДУЛЯ, V8 хранит объектом в куче, и каждая запись в него — аллокация;
 * ровно так шестьсот байт мусора в тик однажды и появились, причём в коде,
 * где не было ни одной фигурной скобки.
 *
 * Как меряем. Рост `heapUsed` за окно фиксированной длины, много раз, минимум
 * по окнам — и окна берутся до тех пор, пока замер не устоится.
 *
 * Одного окна не хватает: как только тик стал делать настоящую работу, в окно
 * начала попадать сборка мусора, и замер показывал то плюс два мегабайта, то
 * МИНУС полтора — то есть отчитывался о моменте сборки, а не об аллокации.
 * Окно в несколько тысяч итераций короче интервала между сборками, а медиана из
 * нескольких окон отбрасывает то, в которое сборка всё-таки попала.
 *
 * Сэмплирующий профилировщик выделений, который напрашивается первым, здесь
 * не годится: на этих объёмах он показывал заведомо аллоцирующему контролю
 * меньше, чем чистому циклу. Грубая мера, которая различает, лучше точной,
 * которая не различает.
 *
 * Требует `--expose-gc` (включён в vitest.config.ts).
 */

import { describe, expect, it } from 'vitest';
import {
  checkInvariants,
  createSnapshot,
  createState,
  hashState,
  saveSnapshot,
  spawnPlayers,
  step,
} from '@dod/sim';
import { makeBot } from '@dod/tools/bots';

/**
 * Длина окна замера.
 *
 * Окно обязано быть длиннее не только ступеньки роста кучи, но и ПРОГРЕВА
 * внутри самого окна, и второе оказалось решающим.
 *
 * Принудительная сборка мусора перед каждым окном сбрасывает V8 обратно к
 * нижнему ярусу компиляции: инлайн-кэши и оптимизированный код строятся
 * заново на всех ветках, которые тик успевает задеть. Пока это происходит,
 * каждое дробное промежуточное значение живёт отдельным объектом в куче — и
 * короткое окно меряет ровно эту служебную работу, а не аллокацию.
 *
 * Замерено на этом самом коде, пять окон подряд, минимум по ним:
 *
 *   окно  4000 → 111 байт на тик
 *   окно  8000 → 144
 *   окно 16000 → 4.8
 *   окно 32000 → 24.5
 *
 * Настоящая аллокация не зависит от длины окна по определению: она приходится
 * на итерацию. Падение в двадцать раз при вчетверо более длинном окне —
 * признак прогрева, и ничего больше.
 *
 * Цена ошибки известна и уплачена: на четырёх тысячах гейт выдал 357.816 байт
 * на тик ОДИНАКОВО на windows-раннере CI и на раннере выкатки — тик
 * детерминирован, значит детерминирован и мусор непрогретого тика, — и тот же
 * самый коммит прошёл при повторном запуске. Красный деплой без единой строки
 * изменений в ядре.
 */
const WINDOW = 16_000;
/**
 * Потолок числа окон, а не их количество.
 *
 * Замер идёт, пока не устоится (см. `bytesPerIteration`), и на здоровом коде
 * это восемь-десять окон. Потолок нужен ровно для обратного случая: код,
 * который аллоцирует на самом деле, не устоится никогда, и без потолка тест
 * висел бы вместо того, чтобы покраснеть.
 *
 * Двадцать, а не шестьдесят: окно выросло вчетверо, и худший случай обязан
 * остаться примерно тем же по времени. Здоровый код выходит на схождении с
 * первых окон и до потолка не доходит вовсе.
 */
const MAX_ROUNDS = 20;
/**
 * Сколько окон подряд должны уложиться в порог, чтобы замеру верить.
 *
 * Одного мало: рост кучи меряется ступенями, и одно случайно чистое окно
 * бывает и у аллоцирующего цикла. Двух подряд — уже нет.
 */
const CALM_ROUNDS = 2;

/**
 * Потолок байт на итерацию.
 *
 * Не ноль: `heapUsed` растёт ступенями, и пара десятков байт на итерацию —
 * это шум замера. Систематическая аллокация даёт сотни байт, разница на
 * порядок, поэтому порог различает уверенно, а не балансирует на грани.
 */
const MAX_BYTES_PER_ITERATION = 64;

/**
 * Свой лимит времени: замер здесь долгий по построению.
 *
 * Десяток окон по четыре тысячи итераций с принудительной сборкой мусора
 * между ними — это секунды. В умолчание Vitest замер укладывался случайно, а
 * после обновления перестал и начал падать по таймауту, то есть отчитываться
 * о времени прогона вместо аллокаций. Уменьшать окна нельзя: на коротких
 * ступенька роста кучи снова становится шумом.
 *
 * Запас взят под худший случай — `MAX_ROUNDS` окон, которые набирает только
 * падающий замер. Здоровый выходит из цикла на схождении и до этого потолка
 * не доходит, поэтому запас ничего не стоит. Платить им разумнее, чем
 * получить падение по таймауту вместо внятной цифры аллокации.
 */
const TIMEOUT = 180_000;

const gc = globalThis.gc;

/**
 * Байт на итерацию: САМОЕ ЧИСТОЕ из окон, а не медиана по ним.
 *
 * Куча в процессе общая, и рядом работают соседние файлы набора: их прогрев,
 * их скрытые классы, их отложенная компиляция — всё это растит `heapUsed`
 * внутри нашего окна и приписывается измеряемому циклу. На разработческой
 * машине это единицы байт, на общем раннере CI доходило до семисот — и тест
 * падал не на аллокации, а на соседях.
 *
 * Минимум устойчив к такой помехе ровно потому, что помеха односторонняя:
 * чужая работа может только ДОБАВИТЬ роста, убавить она его не может. У
 * чистого цикла хотя бы одно окно оказывается неиспорченным и даёт почти
 * ноль; у цикла, который аллоцирует сам, грязны все окна без исключения, и
 * минимум остаётся высоким. Проверку на заведомо аллоцирующем контроле ниже
 * это подтверждает.
 *
 * ЧИСЛО ОКОН НЕ ФИКСИРОВАНО, и это главное в замере.
 *
 * Самая крупная односторонняя помеха — не соседи по процессу, а собственный
 * оптимизатор V8. Пока тик не прошёл TurboFan, каждое дробное промежуточное
 * значение в нём живёт отдельным объектом в куче: под `--max-opt=2` тот же
 * самый тик показывает сотни байт, под полным набором ярусов — единицы.
 * Разница не в коде, а в том, успел ли оптимизатор.
 *
 * Успевает он по числу выполнений и в фоновом потоке, то есть на загруженном
 * общем раннере — позже, чем на разработческой машине. Фиксированные семь
 * окон после фиксированного прогрева это и означали: замер отчитывался о
 * ЯРУСЕ КОМПИЛЯЦИИ, а не об аллокации. Отсюда 520 байт на тик, одинаковые до
 * третьей цифры на macOS и Windows (тик детерминирован, значит и мусор
 * неоптимизированного тика детерминирован) — и зелень на тех же прогонах,
 * где оптимизатор успел. Ненадёжно в обе стороны: настоящая регрессия
 * прошла бы ровно так же незамеченной, если бы её маскировало окно похуже.
 *
 * Поэтому окна берутся не по счёту, а до тех пор, пока замер не устоится:
 * `CALM_ROUNDS` окон подряд ниже порога — ответ получен. Медленной машине это
 * стоит лишних окон, а не красного теста; аллоцирующему коду не помогает
 * никак, потому что оптимизатор аллокацию не убирает — он убирает лишь свою
 * собственную. Не устоялось за `MAX_ROUNDS` — это и есть падение, и минимум
 * по всем окнам показывает, насколько всё плохо.
 */
function bytesPerIteration(fn: () => void, limit = MAX_BYTES_PER_ITERATION): number {
  // Первое окно выбрасывается: в нём догреваются скрытые классы и
  // оптимизатор, и оно систематически дороже остальных.
  let best = Infinity;
  let calm = 0;
  for (let r = 0; r <= MAX_ROUNDS; r++) {
    // Дважды: первый проход освобождает, второй добирает то, что стало
    // недостижимым в первом.
    gc?.();
    gc?.();
    const before = process.memoryUsage().heapUsed;
    for (let i = 0; i < WINDOW; i++) fn();
    const growth = (process.memoryUsage().heapUsed - before) / WINDOW;
    if (r === 0) continue;
    if (growth < best) best = growth;
    if (growth >= limit) {
      calm = 0;
      continue;
    }
    if (++calm === CALM_ROUNDS) break;
  }
  return best;
}

/**
 * Прогрев: длинный намеренно.
 *
 * Пока V8 не оптимизировал функцию, КАЖДОЕ дробное промежуточное значение в
 * ней живёт объектом в куче. Ядро считает дробями много — расстояния, доли,
 * силы расталкивания, — и в неоптимизированном виде тик честно аллоцирует
 * сотни байт, не имея в себе ни одного литерала. Порог такого не переживает.
 *
 * Двух тысяч тиков хватало на разработческой машине и не хватало на общем
 * раннере CI: там тик показывал шестьсот байт против одного локально. Это не
 * дефект ядра, а незавершённый прогрев — и лечится он прогревом, а не
 * поблажкой в пороге.
 *
 * Числом тиков он, однако, не лечится ДО КОНЦА, сколько его ни ставь: ярус
 * компиляции зависит и от загрузки машины, а не только от числа выполнений.
 * Тридцать тысяч — фора, чтобы обычный прогон сходился с первых окон; на
 * случай, когда форы не хватило, есть сам цикл замера.
 */
const WARMUP = 30_000;

function warmRun(players = 4) {
  const s = createState(1, players);
  spawnPlayers(s);
  const bot = makeBot('random', 1, players);
  for (let t = 0; t < WARMUP; t++) step(s, bot.inputs(s));
  return { s, bot };
}

describe('аллокации', () => {
  /*
   * Отсутствие `gc` — отказ настройки, а не повод пропустить проверку.
   *
   * Раньше здесь стоял `describe.skipIf(!gc)`, и это едва не обошлось дорого:
   * Vitest 4 перенёс настройки пула на верхний уровень, `--expose-gc`
   * перестал доезжать до воркера — и весь файл начал молча пропускаться.
   * Набор остался зелёным, перестав проверять главное правило ядра. Падение
   * с внятной причиной честнее зелени, которая ничего не значит.
   */
  it('замер вообще возможен: --expose-gc доехал до воркера', () => {
    expect(gc, 'нет globalThis.gc — проверьте execArgv в vitest.config.ts').toBeTypeOf('function');
  });

  // Контроль над контролем: если замер перестанет ловить объект в цикле, все
  // остальные проверки файла станут зелёными, ничего не проверяя.
  it(
    'замер видит аллокацию, если она есть',
    () => {
      const sink: unknown[] = [];
      const bytes = bytesPerIteration(() => {
        sink.length = 0;
        sink.push({ x: 1, y: 2 });
      });
      expect(bytes).toBeGreaterThan(MAX_BYTES_PER_ITERATION);
    },
    TIMEOUT,
  );

  it(
    'тик боя не аллоцирует',
    () => {
      const { s, bot } = warmRun();
      expect(bytesPerIteration(() => step(s, bot.inputs(s)))).toBeLessThan(MAX_BYTES_PER_ITERATION);
    },
    TIMEOUT,
  );

  it(
    'хеш и снимок не аллоцируют',
    () => {
      const { s } = warmRun();
      const snap = createSnapshot(s);
      for (let i = 0; i < 2000; i++) saveSnapshot(s, snap);

      const bytes = bytesPerIteration(() => {
        hashState(s);
        saveSnapshot(s, snap);
      });
      expect(bytes).toBeLessThan(MAX_BYTES_PER_ITERATION);
    },
    TIMEOUT,
  );

  // Инварианты идут в dev-сборке по тику: замыкание внутри них стоило бы
  // столько же, сколько сама проверка.
  it(
    'проверка инвариантов не аллоцирует',
    () => {
      const { s } = warmRun();
      for (let i = 0; i < 2000; i++) checkInvariants(s);
      expect(bytesPerIteration(() => checkInvariants(s))).toBeLessThan(MAX_BYTES_PER_ITERATION);
    },
    TIMEOUT,
  );
});
