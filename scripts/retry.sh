#!/bin/sh
# Повтор шага, который ходит в сеть.
#
# Зачем. Всё, что тянет зависимости — npm ci, playwright install, apt-get,
# скачивание actionlint — зависит от чужих серверов, и те отвечают 403, 502 и
# обрывом соединения без всякой связи с нашим кодом. Такой прогон краснеет на
# ровном месте, PR стоит до тех пор, пока человек не нажмёт «перезапустить», а
# главный вред глубже: красный CI, который врёт через раз, перестают читать —
# и тогда он пропускает настоящую поломку.
#
# Повторяются ТОЛЬКО получение зависимостей. Тесты, линтеры и проверки
# детерминизма не повторяются никогда: там повтор превращает плавающий баг —
# самый дорогой класс в этом проекте — в зелёную галочку.
#
#   sh scripts/retry.sh npm ci
#   sh scripts/retry.sh --attempts 5 npx playwright install --with-deps chromium
#
# Пауза растёт втрое (5с, 15с, 45с): мгновенный повтор попадает в ту же
# минуту недоступности зеркала, а ждать зря минуты на каждом PR дорого.

set -e

attempts=3
delay=5

while [ $# -gt 0 ]; do
    case "$1" in
        --attempts)
            attempts="$2"
            [ -n "$attempts" ] || break
            shift 2
            ;;
        --)
            shift
            break
            ;;
        *)
            break
            ;;
    esac
done

if [ $# -eq 0 ]; then
    echo "использование: $0 [--attempts N] команда [аргументы...]" >&2
    exit 2
fi

n=1
while :; do
    "$@" && exit 0
    code=$?

    if [ "$n" -ge "$attempts" ]; then
        echo "::error::«$*» не удалась за $attempts попыток (код $code)" >&2
        exit "$code"
    fi

    echo "::warning::попытка $n из $attempts не удалась (код $code), повтор через ${delay}с: $*" >&2
    sleep "$delay"
    n=$((n + 1))
    delay=$((delay * 3))
done
