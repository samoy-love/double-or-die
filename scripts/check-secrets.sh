#!/bin/sh
# Сканер секретов: одни правила для хука и для CI.
#
# Утёкший ключ чистится переписыванием опубликованной истории и отзывом самого
# ключа — это дороже любого неудобства здесь. Причём заметить утечку обычно
# некому: коммит выглядит обычным, CI зелёный, а ключ уже в истории навсегда.
#
# Почему это отдельный файл, а не тело хука. Локальный хук обходится флагом
# `--no-verify` и не действует на чужих машинах (TECH §12А) — значит, те же
# правила обязаны стоять в CI. А два списка шаблонов, живущих порознь,
# расходятся: правку вносят в один, второй молча остаётся дырявым. Поэтому
# список ровно один, а хук и workflow — два способа его позвать.
#
#   scripts/check-secrets.sh --staged           индекс (pre-commit)
#   scripts/check-secrets.sh --range base..head диапазон коммитов (CI)
#
# Проверяются только ДОБАВЛЯЕМЫЕ строки, а не файлы целиком: иначе проверка
# ругалась бы на давно лежащий в репозитории текст при каждом запуске, и её
# отключили бы через неделю (ROADMAP 0.1.0).

set -e

usage() {
    echo "использование: $0 --staged | --range <base>..<head>" >&2
    exit 2
}

mode=""
range=""

case "$1" in
    --staged)
        mode="staged"
        ;;
    --range)
        mode="range"
        range="$2"
        [ -n "$range" ] || usage
        ;;
    *)
        usage
        ;;
esac

if [ "$mode" = "staged" ]; then
    # Двоичные файлы из диффа выкидываем: искать в них подстроки бессмысленно,
    # а вывод они ломают.
    added="$(git diff --cached --diff-filter=ACM -U0 --no-color -- . \
      | grep -E '^\+' | grep -Ev '^\+\+\+' || true)"
    files="$(git diff --cached --name-only --diff-filter=ACM)"
else
    added="$(git diff --diff-filter=ACM -U0 --no-color "$range" -- . \
      | grep -E '^\+' | grep -Ev '^\+\+\+' || true)"
    files="$(git diff --name-only --diff-filter=ACM "$range")"
fi

# Шаблоны намеренно узкие: широкие («password», «token» где угодно) дают
# ложные срабатывания на комментариях и именах полей, а проверка, которая
# врёт, перестают читать.
#
#   1. Приватные ключи любого вида — самый дорогой случай.
#   2. Токены с узнаваемым префиксом: GitHub, Telegram, AWS, Slack.
#   3. Присваивание секрета непустым литералом в коде и в .env.
patterns='-----BEGIN [A-Z ]*PRIVATE KEY-----
gh[pousr]_[A-Za-z0-9]{16,}
github_pat_[A-Za-z0-9_]{20,}
[0-9]{8,10}:AA[A-Za-z0-9_-]{30,}
AKIA[0-9A-Z]{16}
xox[baprs]-[A-Za-z0-9-]{10,}
(SECRET|TOKEN|PASSWORD|PASSWD|API_KEY|PRIVATE_KEY)[A-Z_]*\s*[=:]\s*["'"'"']?[A-Za-z0-9/+_-]{16,}'

status=0

if [ -n "$added" ]; then
    # Шаблоны уезжают во временный файл и читаются через -f.
    #
    # Не для красоты: первый шаблон начинается с дефисов, и переданный
    # аргументом он был бы принят за опции grep. Ошибку разбора при этом легко
    # не заметить — grep вернёт код 2, а привычное `|| true` превратит его в
    # «совпадений нет». Так проверка и умирает: файл лежит, секреты проходят.
    pfile="$(mktemp)"
    trap 'rm -f "$pfile"' EXIT
    printf '%s\n' "$patterns" > "$pfile"

    set +e
    hits="$(printf '%s\n' "$added" | grep -nEi -f "$pfile")"
    rc=$?
    set -e

    # Коды grep: 0 — нашёл, 1 — не нашёл, всё остальное — сам сломался.
    # Последнее обязано валить проверку: то, что нельзя выполнить, нельзя
    # считать пройденным.
    if [ "$rc" -gt 1 ]; then
        echo "✗ Проверка на секреты не отработала (grep вернул $rc)." >&2
        echo "  Непройденная проверка — не то же самое, что чистая." >&2
        exit 1
    fi

    if [ -n "$hits" ]; then
        echo "✗ Похоже на секрет в добавляемых строках:" >&2
        echo "$hits" | head -10 >&2
        echo >&2
        echo "  Секрет из истории убирается только переписыванием и отзывом ключа." >&2
        echo "  Если это ложное срабатывание — git commit --no-verify." >&2
        status=1
    fi
fi

# Файлы окружения не коммитятся никогда: даже пустой сегодня, завтра он
# наполнится, и правка пройдёт незамеченной.
env_files="$(printf '%s\n' "$files" | grep -E '(^|/)\.env(\.|$)' | grep -v '\.env\.example$' || true)"

if [ -n "$env_files" ]; then
    echo "✗ В изменения попал файл окружения:" >&2
    echo "$env_files" >&2
    echo "  Образец без значений — .env.example; настоящий .env остаётся у вас." >&2
    status=1
fi

if [ "$status" -eq 0 ]; then
    echo "секреты: чисто"
fi
exit "$status"
