/**
 * Каталог экранов и состояний игры — единственный список того, что снимается.
 *
 * Заведён ради ревью. Раньше каждый прогон скриншотов был одноразовым
 * скриптом: агент писал его заново, снимал три-четыре экрана, которые помнил,
 * и по ним делал выводы обо всей игре. Состояния, о которых он не вспомнил, —
 * пустой фокус, долг, проклятие, мёртвая колонка HUD, торг без апгрейдов —
 * не проверял никто и никогда.
 *
 * Каталог — ДАННЫЕ, а не код съёмки. Поэтому его читает и раннер
 * (`scripts/shots.ts`), и тест (`tests/screens.test.ts`), который следит за
 * тем, чтобы новая фаза забега не появилась без своего сценария.
 *
 * **Правило: новый экран или состояние добавляется сюда в том же изменении,
 * что и сам экран.** Не покрытое здесь не попадёт ни в одно ревью — а ревью в
 * этом проекте идут постоянно и агентами, которые видят ровно то, что снято.
 */

/** Фазы забега — теми же числами, что `RunPhase` в ядре. */
export const enum Phase {
  Door = 0,
  Fight = 1,
  Settlement = 2,
  Reward = 3,
  Boss = 4,
  HouseCut = 5,
  Summary = 6,
  /** Не фаза ядра: меню, справка, настройки живут в клиенте. */
  Client = 100,
}

/**
 * Шаг сценария.
 *
 * Декларативно, а не колбэком: шаги уезжают в браузер через `page.evaluate`, и
 * функция, замкнувшая переменные раннера, туда не доедет. Заодно каталог
 * читается тестом, которому браузер не нужен вовсе.
 */
export type Step =
  /** Вызвать метод отладочного API: `{ call: 'give', args: [{ chips: 200 }] }`. */
  | { readonly call: string; readonly args?: readonly unknown[] }
  /** Нажать клавишу по-человечески: с удержанием на кадр. */
  | { readonly key: string }
  /** Прошагать симуляцию. */
  | { readonly ticks: number }
  /** Шагать до нужной фазы, но не дольше `limit` тиков. */
  | { readonly waitPhase: Phase; readonly limit?: number };

export interface Screen {
  /** Имя файла снимка и адрес состояния в отчётах ревью. */
  readonly id: string;
  /** Человеческое название: попадает в индекс рядом со снимком. */
  readonly title: string;
  /** Какую фазу забега показывает состояние. */
  readonly phase: Phase;
  /** Что должно быть видно на кадре — вопрос, на который отвечает ревьюер. */
  readonly checks: readonly string[];
  readonly steps: readonly Step[];
  /**
   * Приблизить кадр к Крупье вместо снимка арены целиком — для мелких на
   * игровом разрешении деталей (жест, ~60×90 единиц), которые обычным
   * снимком не разглядеть. Половина стороны рамки вокруг него, в единицах
   * арены (`state().ace.x/y` — тот же мир), плюс кратность увеличения;
   * `shots.ts` читает актуальную позицию Крупье перед снимком САМ — здесь
   * не координаты, а требуемое поле обзора вокруг него.
   */
  readonly zoom?: { readonly halfW: number; readonly halfH: number; readonly scale: number };
}

/** Свежий забег без обучения: подсказки коуча снимаются отдельными сценариями. */
const RUN = (seed: number, players = 1): readonly Step[] => [
  { call: 'learned' },
  { call: 'newRun', args: [{ seed, players }] },
  { call: 'stable', args: [true] },
  { call: 'mute', args: [true] },
];

/**
 * Тиков до ЖИВОГО боя, а не до паузы начала комнаты.
 *
 * Комната открывается паузой `WAVE.firstWaveGapTicks` (2.5 с = 150 тиков), и
 * взятое в ней пари само поднимает экран расчёта поверх арены: сценарии,
 * снимавшие «красную зону», «плашку сделки» и «поштучный забор» после
 * `{ ticks: 120 }`, показывали титул «Пауза» и затемнение, а не то, что обещали.
 * 210 — пауза плюс секунда запаса: первая волна уже пошла, расчёта нет.
 */
